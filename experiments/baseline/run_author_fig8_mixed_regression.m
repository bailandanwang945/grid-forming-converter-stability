function result = run_author_fig8_mixed_regression(fixtureRoot)
%RUN_AUTHOR_FIG8_MIXED_REGRESSION Evaluate the controlled Fig. 8 fixture.
%   This clean-clone regression applies the corrected E/C/F transform and
%   sampled mixed gain-phase screening to D=0.05 and D=0.5 cases derived
%   from one author workbook. Phase conclusions remain conditional on the
%   explicitly recorded seed and nearest-neighbor branch assumption.

    projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
    addpath(fullfile(projectRoot, 'src'), '-begin');
    if nargin < 1
        fixtureRoot = [];
    end
    fixture = load_author_fig8_raw_fixture(fixtureRoot);
    weightingConfiguration = struct( ...
        'BaseAngularFrequency', fixture.baseAngularFrequency, ...
        'VirtualResistance', 0.01, ...
        'VirtualReactance', 0.1, ...
        'NormalizeAtBase', true);
    transformationMetadata = struct( ...
        'frameConventionId', ...
            "cifelli-anta-author-global-synchronous-dq-v1", ...
        'converterCurrentDirection', "network-to-converter", ...
        'networkCurrentDirection', "converter-to-network", ...
        'powerConvention', "load-positive");
    evaluatorConventions = struct( ...
        'frameConventionId', ...
            "cifelli-anta-author-global-synchronous-dq-v1", ...
        'currentDirection', "network-to-converter", ...
        'powerDirection', "load-positive", ...
        'sBase', 1, 'vBase', 1, ...
        'fBase', fixture.baseAngularFrequency/(2*pi), ...
        'matrixType', "admittance", ...
        'globalFrameId', "author-infinite-bus-global-dq");
    preconditions = struct( ...
        'openLoopStable', false, ...
        'realRationalProper', false, ...
        'transformationWellDefined', false, ...
        'networkInverseStable', false, ...
        'noRhpCancellation', false, ...
        'endpointsCovered', false, ...
        'fullFrequencyCoverage', false);

    caseCount = numel(fixture.cases);
    caseResults = cell(caseCount, 1);
    for caseIndex = 1:caseCount
        rawCase = fixture.cases(caseIndex);
        weighting = buildVirtualImpedanceWeightingSamples( ...
            rawCase.frequenciesHz, weightingConfiguration);
        shaping = buildMixedLoopShapingSamples( ...
            {rawCase.converterResponse}, rawCase.networkResponse, ...
            rawCase.frequenciesHz, {fixture.operatingPoint}, ...
            {weighting.responses}, struct( ...
                'ConventionMetadata', transformationMetadata));
        [converterSeed, converterSeedIndex] = firstResolvedPhaseSeed( ...
            shaping.converterResponses{1});
        inverseNetwork = inverseResponse(shaping.networkResponse);
        [networkSeed, networkSeedIndex] = firstResolvedPhaseSeed( ...
            inverseNetwork);
        evaluatorOptions = struct( ...
            'PhaseCenterSeeds', struct( ...
                'converterCenters', converterSeed, ...
                'networkInverseCenter', networkSeed), ...
            'PhaseBranchOptions', struct('SeedFrequencyIndices', ...
                [converterSeedIndex; networkSeedIndex]), ...
            'PhaseSeedProvenance', ...
                "first-resolved-grid-point-principal-center");
        screening = evaluateMixedGainPhaseSamples( ...
            shaping.converterResponses, shaping.networkResponse, ...
            rawCase.frequenciesHz, evaluatorConventions, ...
            preconditions, evaluatorOptions);

        poleRows = rawCase.spectrum(rawCase.spectrum.value_type == ...
            "closed-loop-pole", :);
        maximumRealPoleHz = max(poleRows.real_Hz);
        caseResults{caseIndex} = struct( ...
            'caseId', rawCase.caseId, ...
            'damping', rawCase.damping, ...
            'closedLoopStableOnPinnedSpectrum', maximumRealPoleHz <= 0, ...
            'maximumRealPoleHz', maximumRealPoleHz, ...
            'converterPhaseSeedIndex', converterSeedIndex, ...
            'converterPhaseSeedFrequencyHz', ...
                rawCase.frequenciesHz(converterSeedIndex), ...
            'networkPhaseSeedIndex', networkSeedIndex, ...
            'networkPhaseSeedFrequencyHz', ...
                rawCase.frequenciesHz(networkSeedIndex), ...
            'maximumTransformationConditionNumber', ...
                max(shaping.transformationConditionNumbers(:)), ...
            'maximumInterconnectionResidual', ...
                max(shaping.interconnectionResidual), ...
            'shaping', shaping, ...
            'screening', screening);
    end
    result = struct( ...
        'cases', vertcat(caseResults{:}), ...
        'fixtureId', string(fixture.manifest.fixtureId), ...
        'screeningBoundary', ...
            "conditional finite-grid screening, not theorem confirmation", ...
        'method', "author-fig8-controlled-damping-mixed-regression-v1");
end

function inverse = inverseResponse(response)
    pointCount = size(response, 3);
    inverse = complex(zeros(size(response)));
    identity = eye(size(response, 1));
    for index = 1:pointCount
        inverse(:, :, index) = response(:, :, index)\identity;
    end
end

function [seed, seedIndex] = firstResolvedPhaseSeed(response)
    for index = 1:size(response, 3)
        phase = computeStrictSectorialPhaseInterval(response(:, :, index));
        if phase.status == "resolved"
            seed = phase.branchCenter;
            seedIndex = index;
            return;
        end
    end
    error('Fig8Regression:NoResolvedPhaseSeed', ...
        'No strict-sectorial phase sample is available for branch seeding.');
end
