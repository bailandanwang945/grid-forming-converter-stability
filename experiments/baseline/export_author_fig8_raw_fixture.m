function manifest = export_author_fig8_raw_fixture( ...
        sourceWorkspacePath, outputRoot, options)
%EXPORT_AUTHOR_FIG8_RAW_FIXTURE Export a controlled D=0.05/0.5 fixture.
%   The source workspace is generated from one Fig. 8 workbook while only
%   VSM damping D changes. Ignored MAT/LTI objects are converted to tracked,
%   deterministic CSV and JSON files. The existing D=0.05 author baseline
%   is independently cross-checked before any fixture is written.

    projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
    if nargin < 1 || isempty(sourceWorkspacePath)
        sourceWorkspacePath = fullfile(projectRoot, 'results', 'schur', ...
            'damping-continuation', 'damping_continuation_workspace.mat');
    end
    if nargin < 2 || isempty(outputRoot)
        outputRoot = fullfile(projectRoot, 'experiments', 'baseline', ...
            'fixtures');
    end
    if nargin < 3 || isempty(options)
        options = struct();
    end
    options = validateOptions(options);
    sourceWorkspacePath = char(sourceWorkspacePath);
    outputRoot = char(outputRoot);

    assert(isfile(sourceWorkspacePath), 'Fig8Fixture:MissingWorkspace', ...
        'Run run_inf_bus_damping_continuation before exporting.');
    data = load(sourceWorkspacePath);
    validateSource(data);
    crossCheckDamping005(data, projectRoot, options.FrequenciesHz);

    caseIds = ["fig8_D_0p05", "fig8_D_0p5"];
    points = {data.lowPoint, data.highPoint};
    frequencyRows = cell(2, 1);
    spectrumRows = cell(2, 1);
    for caseIndex = 1:2
        converterResponse = evaluateResponse( ...
            points{caseIndex}.converterMatrix, options.FrequenciesHz);
        networkResponse = evaluateResponse( ...
            data.networkMatrix, options.FrequenciesHz);
        assert(all(isfinite(converterResponse(:))) && ...
            all(isfinite(networkResponse(:))), ...
            'Fig8Fixture:NonfiniteResponse', ...
            'All exported frequency-response values must be finite.');
        frequencyRows{caseIndex} = makeFrequencyRows(caseIds(caseIndex), ...
            points{caseIndex}.damping, options.FrequenciesHz, ...
            converterResponse, networkResponse);
        spectrumRows{caseIndex} = makeSpectrumRows(caseIds(caseIndex), ...
            points{caseIndex});
    end
    frequencyRows = vertcat(frequencyRows{:});
    spectrumRows = vertcat(spectrumRows{:});
    frequencyRowCount = sum(arrayfun( ...
        @(rows) numel(rows.frequency), frequencyRows));

    if ~isfolder(outputRoot)
        mkdir(outputRoot);
    end
    frequencyPath = fullfile(outputRoot, ...
        'author_fig8_raw_frequency_response.csv');
    spectrumPath = fullfile(outputRoot, 'author_fig8_spectrum.csv');
    manifestPath = fullfile(outputRoot, ...
        'author_fig8_fixture_manifest.json');
    writeFrequencyCsv(frequencyPath, frequencyRows, options.NumericFormat);
    writeSpectrumCsv(spectrumPath, spectrumRows, options.NumericFormat);

    powerFlow = data.powerFlow(:).';
    voltage = powerFlow(3)*exp(1i*powerFlow(4));
    current = (powerFlow(1)-1i*powerFlow(2))/conj(voltage);
    manifest = struct( ...
        'schemaVersion', "1.0.0", ...
        'fixtureId', "cifelli-anta-fig8-damping-controlled-v1", ...
        'authorRepository', "Cifelli-Anta released companion code", ...
        'authorTag', "v1.0.0", ...
        'authorCommit', "ef67c7a4ac84e4e1142e95b072d241db89eb64ba", ...
        'sourceWorkbook', ...
            "external/cifelli-small-gain-phase/UserData_inf_bus_Fig_8.xlsm", ...
        'sourceWorkbookSha256', ...
            "5DD0FACCA95A134090EF5CDF5F5ACB2EB20A681F9CCA36ACCF182E54D751BFB2", ...
        'simplusProvenance', struct( ...
            'versionMarker', "v2026-Mar-9", ...
            'commit', "unavailable-local-snapshot", ...
            'sourceBoundary', ...
                "local snapshot without nested Git metadata", ...
            'authorClassOverlay', "GridFormingVSI.m from author release"), ...
        'sourceWorkspaceRelativePath', ...
            "results/schur/damping-continuation/damping_continuation_workspace.mat", ...
        'matlabRelease', string(version('-release')), ...
        'frequencyGrid', struct( ...
            'minimumHz', options.FrequenciesHz(1), ...
            'maximumHz', options.FrequenciesHz(end), ...
            'pointCountPerCase', numel(options.FrequenciesHz), ...
            'spacing', "logarithmic"), ...
        'numericFormat', string(options.NumericFormat), ...
        'poleExclusionThresholdHz', 1e-7, ...
        'baseAngularFrequency', data.baseAngularFrequency, ...
        'powerFlow', struct('P', powerFlow(1), 'Q', powerFlow(2), ...
            'V', powerFlow(3), 'phi', powerFlow(4), 'omega', powerFlow(5), ...
            'convention', "load-positive"), ...
        'derivedOperatingPoint', struct( ...
            'vd', real(voltage), 'vq', imag(voltage), ...
            'id', real(current), 'iq', imag(current), ...
            'definition', "v=V*exp(j*phi); i=(P-jQ)/conj(v)", ...
            'convention', "author-load-positive"), ...
        'portConventions', struct( ...
            'frameConventionId', ...
                "cifelli-anta-author-global-synchronous-dq-v1", ...
            'converterCurrentDirection', "network-to-converter", ...
            'networkCurrentDirection', "converter-to-network", ...
            'powerConvention', "load-positive", ...
            'matrixType', "admittance"), ...
        'caseIds', caseIds, ...
        'dampingValues', [data.lowPoint.damping, data.highPoint.damping], ...
        'frequencyResponseRowCount', frequencyRowCount, ...
        'spectrumRowCount', size(spectrumRows, 1));
    writelines(jsonencode(manifest, PrettyPrint=true), manifestPath);
    fprintf('FIG8_FIXTURE frequency_rows=%d spectrum_rows=%d path=%s\n', ...
        frequencyRowCount, size(spectrumRows, 1), outputRoot);
end

function options = validateOptions(options)
    if ~(isstruct(options) && isscalar(options))
        error('Fig8Fixture:InvalidOptions', 'options must be a scalar struct.');
    end
    defaults = struct('FrequenciesHz', ...
        logspace(log10(1e-3), log10(1e4), 1000).', ...
        'NumericFormat', '%.17g');
    names = fieldnames(defaults);
    unknownNames = setdiff(fieldnames(options), names);
    assert(isempty(unknownNames), 'Fig8Fixture:UnknownOption', ...
        'Unknown option: %s.', firstOrEmpty(unknownNames));
    for index = 1:numel(names)
        name = names{index};
        if ~isfield(options, name)
            options.(name) = defaults.(name);
        end
    end
    frequencies = options.FrequenciesHz;
    assert(isnumeric(frequencies) && isreal(frequencies) && ...
        isvector(frequencies) && ~isempty(frequencies) && ...
        all(isfinite(frequencies)) && all(frequencies >= 0) && ...
        all(diff(frequencies(:)) > 0), 'Fig8Fixture:InvalidFrequencyGrid', ...
        'FrequenciesHz must be finite, nonnegative, and strictly increasing.');
    options.FrequenciesHz = frequencies(:);
    assert((ischar(options.NumericFormat) && isrow(options.NumericFormat)) || ...
        (isstring(options.NumericFormat) && isscalar(options.NumericFormat)), ...
        'Fig8Fixture:InvalidNumericFormat', ...
        'NumericFormat must be a text scalar.');
    options.NumericFormat = char(options.NumericFormat);
end

function value = firstOrEmpty(values)
    if isempty(values)
        value = '';
    else
        value = values{1};
    end
end

function validateSource(data)
    required = ["lowPoint", "highPoint", "networkMatrix", ...
        "powerFlow", "baseAngularFrequency", "summary"];
    assert(all(isfield(data, required)), 'Fig8Fixture:OutdatedWorkspace', ...
        'The damping workspace must be regenerated with endpoint models.');
    validatePoint(data.lowPoint, 0.05);
    validatePoint(data.highPoint, 0.5);
    assert(isequal(size(data.networkMatrix), [2, 2]), ...
        'Fig8Fixture:InvalidNetwork', 'networkMatrix must be 2-by-2.');
    assert(isnumeric(data.powerFlow) && numel(data.powerFlow) == 5 && ...
        all(isfinite(data.powerFlow)) && data.powerFlow(3) > 0, ...
        'Fig8Fixture:InvalidPowerFlow', ...
        'powerFlow must contain finite [P,Q,V,phi,w] with V>0.');
    assert(isnumeric(data.baseAngularFrequency) && ...
        isscalar(data.baseAngularFrequency) && ...
        isfinite(data.baseAngularFrequency) && ...
        data.baseAngularFrequency > 0, 'Fig8Fixture:InvalidBaseFrequency', ...
        'baseAngularFrequency must be finite and positive.');
end

function validatePoint(point, expectedDamping)
    required = ["damping", "converterMatrix", "dynamicPolesHz", ...
        "dynamicReturnZerosHz", "dominantPoleHz", "dominantReturnZeroHz"];
    assert(isstruct(point) && isscalar(point) && ...
        all(isfield(point, required)), 'Fig8Fixture:InvalidEndpoint', ...
        ['Each endpoint must contain models and dynamic spectra after ', ...
         'the documented trivial-zero-mode filter.']);
    assert(abs(point.damping-expectedDamping) <= 1e-12, ...
        'Fig8Fixture:UnexpectedDamping', ...
        'The controlled endpoints must be D=0.05 and D=0.5.');
    assert(isequal(size(point.converterMatrix), [2, 2]) && ...
        ~isempty(point.dynamicPolesHz) && ...
        ~isempty(point.dynamicReturnZerosHz), ...
        'Fig8Fixture:InvalidEndpoint', ...
        'Each endpoint must contain a 2-by-2 converter and spectra.');
end

function crossCheckDamping005(data, projectRoot, frequenciesHz)
    baselinePath = fullfile(projectRoot, 'results', 'baseline', 'unstable', ...
        'baseline_workspace.mat');
    assert(isfile(baselinePath), 'Fig8Fixture:MissingUnstableBaseline', ...
        'Run run_inf_bus_baseline("unstable") before exporting.');
    baseline = load(baselinePath, 'Yc', 'Ynet', 'GsysSs', ...
        'powerFlow', 'baseAngularFrequency');
    required = ["Yc", "Ynet", "GsysSs", "powerFlow", ...
        "baseAngularFrequency"];
    assert(all(isfield(baseline, required)), ...
        'Fig8Fixture:OutdatedUnstableBaseline', ...
        'The unstable baseline workspace is missing required data.');

    oldConverter = evaluateResponse(baseline.Yc, frequenciesHz);
    newConverter = evaluateResponse(data.lowPoint.converterMatrix, frequenciesHz);
    oldNetwork = evaluateResponse(baseline.Ynet, frequenciesHz);
    newNetwork = evaluateResponse(data.networkMatrix, frequenciesHz);
    assertClose(oldConverter, newConverter, 1e-10, 1e-9, ...
        'Fig8Fixture:Damping005ConverterMismatch');
    assertClose(oldNetwork, newNetwork, 1e-10, 1e-9, ...
        'Fig8Fixture:Damping005NetworkMismatch');
    assertClose(baseline.powerFlow, data.powerFlow, 1e-12, 0, ...
        'Fig8Fixture:Damping005PowerFlowMismatch');
    assertClose(baseline.baseAngularFrequency, data.baseAngularFrequency, ...
        1e-12, 0, 'Fig8Fixture:Damping005BaseMismatch');

    oldPoles = eig(baseline.GsysSs.A)/(2*pi);
    oldPoles = oldPoles(abs(oldPoles) > 1e-7);
    compareSpectra(oldPoles, data.lowPoint.dynamicPolesHz, ...
        'Fig8Fixture:Damping005PoleMismatch');
    oldZeros = tzero(ss(minreal(baseline.Yc+baseline.Ynet)))/(2*pi);
    oldZeros = oldZeros(abs(oldZeros) > 1e-7);
    compareSpectra(oldZeros, data.lowPoint.dynamicReturnZerosHz, ...
        'Fig8Fixture:Damping005ZeroMismatch');
end

function assertClose(actual, expected, absoluteTolerance, ...
        relativeTolerance, identifier)
    difference = max(abs(actual(:)-expected(:)));
    scale = max([1; abs(actual(:)); abs(expected(:))]);
    assert(difference <= absoluteTolerance+relativeTolerance*scale, ...
        identifier, 'Numerical mismatch %.17g exceeds tolerance.', difference);
end

function compareSpectra(actual, expected, identifier)
    actual = sortSpectrum(actual);
    expected = sortSpectrum(expected);
    assert(numel(actual) == numel(expected), identifier, ...
        'Spectrum lengths differ.');
    assertClose(actual, expected, 1e-8, 0, identifier);
end

function values = sortSpectrum(values)
    values = values(:);
    [~, order] = sortrows([-real(values), imag(values)], [1, 2]);
    values = values(order);
end

function response = evaluateResponse(model, frequenciesHz)
    response = complex(zeros(2, 2, numel(frequenciesHz)));
    for index = 1:numel(frequenciesHz)
        response(:, :, index) = evalfr(model, 1i*2*pi*frequenciesHz(index));
    end
end

function rows = makeFrequencyRows(caseId, damping, frequenciesHz, yc, ynet)
    pointCount = numel(frequenciesHz);
    rows = struct( ...
        'caseId', repmat(caseId, pointCount, 1), ...
        'damping', repmat(damping, pointCount, 1), ...
        'frequency', frequenciesHz(:), ...
        'values', zeros(pointCount, 16));
    rows.values = [matrixColumns(yc), matrixColumns(ynet)];
end

function columns = matrixColumns(response)
    columns = [ ...
        real(squeeze(response(1, 1, :))), imag(squeeze(response(1, 1, :))), ...
        real(squeeze(response(1, 2, :))), imag(squeeze(response(1, 2, :))), ...
        real(squeeze(response(2, 1, :))), imag(squeeze(response(2, 1, :))), ...
        real(squeeze(response(2, 2, :))), imag(squeeze(response(2, 2, :)))];
end

function rows = makeSpectrumRows(caseId, point)
    poles = sortSpectrum(point.dynamicPolesHz);
    zerosHz = sortSpectrum(point.dynamicReturnZerosHz);
    rows = [spectrumTypeRows(caseId, point.damping, ...
        "closed-loop-pole", poles); ...
        spectrumTypeRows(caseId, point.damping, "return-zero", zerosHz)];
end

function rows = spectrumTypeRows(caseId, damping, valueType, values)
    maximumRealPart = max(real(values));
    dominant = abs(real(values)-maximumRealPart) <= 1e-10;
    count = numel(values);
    rows = table(repmat(caseId, count, 1), repmat(damping, count, 1), ...
        repmat(valueType, count, 1), (1:count).', real(values), imag(values), ...
        dominant, 'VariableNames', {'case_id', 'damping_D', 'value_type', ...
        'value_index', 'real_Hz', 'imag_Hz', 'is_dominant_pair'});
end

function writeFrequencyCsv(path, rows, numericFormat)
    fileId = fopen(path, 'w', 'n', 'UTF-8');
    assert(fileId >= 0, 'Fig8Fixture:WriteFailed', ...
        'Could not open frequency-response CSV.');
    cleanup = onCleanup(@() fclose(fileId));
    fprintf(fileId, ['case_id,damping_D,frequency_Hz,', ...
        'Yc11_real,Yc11_imag,Yc12_real,Yc12_imag,', ...
        'Yc21_real,Yc21_imag,Yc22_real,Yc22_imag,', ...
        'Ynet11_real,Ynet11_imag,Ynet12_real,Ynet12_imag,', ...
        'Ynet21_real,Ynet21_imag,Ynet22_real,Ynet22_imag\n']);
    rowFormat = ['%s,', strjoin(repmat({numericFormat}, 1, 18), ','), '\n'];
    for caseIndex = 1:numel(rows)
        for index = 1:numel(rows(caseIndex).frequency)
            fprintf(fileId, rowFormat, char(rows(caseIndex).caseId(index)), ...
                rows(caseIndex).damping(index), ...
                rows(caseIndex).frequency(index), ...
                rows(caseIndex).values(index, :));
        end
    end
end

function writeSpectrumCsv(path, rows, numericFormat)
    fileId = fopen(path, 'w', 'n', 'UTF-8');
    assert(fileId >= 0, 'Fig8Fixture:WriteFailed', ...
        'Could not open spectrum CSV.');
    cleanup = onCleanup(@() fclose(fileId));
    fprintf(fileId, ['case_id,damping_D,value_type,value_index,', ...
        'real_Hz,imag_Hz,is_dominant_pair\n']);
    rowFormat = ['%s,', numericFormat, ',%s,%d,', numericFormat, ',', ...
        numericFormat, ',%d\n'];
    for index = 1:height(rows)
        fprintf(fileId, rowFormat, char(rows.case_id(index)), ...
            rows.damping_D(index), char(rows.value_type(index)), ...
            rows.value_index(index), rows.real_Hz(index), ...
            rows.imag_Hz(index), rows.is_dominant_pair(index));
    end
end
