function summary = run_inf_bus_damping_continuation()
%RUN_INF_BUS_DAMPING_CONTINUATION Continue the Fig. 8 model in physical damping.
%   The Fig. 8 network, load, operating point, inertia, and Q-control mode
%   are held fixed. Only Para.Dw (Apparatus!I39, used as VSM damping D by
%   the author's GridFormingVSI model) is varied.

    projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
    authorRoot = fullfile(projectRoot, 'external', 'cifelli-small-gain-phase');
    simplusRoot = fullfile(projectRoot, 'external', 'simplus-grid-tool');
    outputRoot = fullfile(projectRoot, 'results', 'schur', 'damping-continuation');
    runtimeRoot = fullfile(projectRoot, 'tmp', 'damping-continuation', ...
        'runtime-simplus-grid-tool');
    inputName = 'UserData_inf_bus_Fig_8.xlsm';

    oldPath = path;
    oldFolder = pwd;
    oldFigureVisibility = get(groot, 'defaultFigureVisible');
    cleanup = onCleanup(@() restoreEnvironment( ...
        oldPath, oldFolder, oldFigureVisibility, runtimeRoot)); %#ok<NASGU>

    prepareRuntimeTool(simplusRoot, authorRoot, runtimeRoot, inputName);
    path(oldPath);
    rmpathIfPresent(genpath(simplusRoot));
    addpath(genpath(runtimeRoot), '-begin');
    addpath(authorRoot, '-begin');
    set(groot, 'defaultFigureVisible', 'off');
    cd(runtimeRoot);
    rehash;

    resolvedClass = which('SimplusGT.Class.GridFormingVSI');
    expectedClass = fullfile(runtimeRoot, '+SimplusGT', '+Class', ...
        'GridFormingVSI.m');
    assert(strcmpi(resolvedClass, expectedClass), ...
        'DampingContinuation:WrongClass', ...
        'The isolated author class was not resolved.');

    UserDataName = 'UserData'; %#ok<NASGU>
    UserDataType = 1; %#ok<NASGU>
    NumApparatus = NaN; %#ok<NASGU>
    ApparatusType = {}; %#ok<NASGU>
    Para = {}; %#ok<NASGU>
    SimplusGT.Toolbox.Main();

    assert(NumApparatus == 2 && ApparatusType{2} == 20, ...
        'DampingContinuation:UnexpectedSystem', ...
        'The input is not the expected GFM-infinite-bus system.');
    assert(abs(Para{2}.Dw - 0.05) < 1e-12, ...
        'DampingContinuation:UnexpectedInitialDamping', ...
        'Fig. 8 workbook no longer has Para.Dw = 0.05.');

    [~, networkMatrix] = ObjYbusDss.GetDSS(ObjYbusDss);
    networkMatrix = networkMatrix(3:end, 3:end);

    dampingGrid = linspace(0.05, 0.5, 19).';
    maximumRealPoleHz = zeros(size(dampingGrid));
    dominantPoleOscillationHz = zeros(size(dampingGrid));
    dominantReturnZeroRealHz = zeros(size(dampingGrid));
    dominantReturnZeroOscillationHz = zeros(size(dampingGrid));

    for index = 1:numel(dampingGrid)
        point = evaluateDamping(dampingGrid(index), Para, ObjGmCell, ...
            ApparatusBus, ApparatusType, ApparatusPowerFlow, Ts, ...
            ListBusNew, Advance, ObjZbusDss, NumBus, networkMatrix);
        maximumRealPoleHz(index) = real(point.dominantPoleHz);
        dominantPoleOscillationHz(index) = abs(imag(point.dominantPoleHz));
        dominantReturnZeroRealHz(index) = real(point.dominantReturnZeroHz);
        dominantReturnZeroOscillationHz(index) = ...
            abs(imag(point.dominantReturnZeroHz));
        fprintf('DAMPING_GRID D=%.6f pole=%.9g+j%.9g Hz\n', ...
            dampingGrid(index), real(point.dominantPoleHz), ...
            abs(imag(point.dominantPoleHz)));
    end

    crossingIndex = find(maximumRealPoleHz(1:end-1) > 0 & ...
        maximumRealPoleHz(2:end) <= 0, 1, 'first');
    assert(~isempty(crossingIndex), ...
        'DampingContinuation:NoCrossing', ...
        'No stability crossing was found on D in [0.05, 0.5].');

    lowerDamping = dampingGrid(crossingIndex);
    upperDamping = dampingGrid(crossingIndex + 1);
    for iteration = 1:28
        middleDamping = (lowerDamping + upperDamping) / 2;
        point = evaluateDamping(middleDamping, Para, ObjGmCell, ...
            ApparatusBus, ApparatusType, ApparatusPowerFlow, Ts, ...
            ListBusNew, Advance, ObjZbusDss, NumBus, networkMatrix);
        if real(point.dominantPoleHz) > 0
            lowerDamping = middleDamping;
        else
            upperDamping = middleDamping;
        end
    end
    criticalDamping = (lowerDamping + upperDamping) / 2;
    criticalPoint = evaluateDamping(criticalDamping, Para, ObjGmCell, ...
        ApparatusBus, ApparatusType, ApparatusPowerFlow, Ts, ...
        ListBusNew, Advance, ObjZbusDss, NumBus, networkMatrix);
    lowPoint = evaluateDamping(0.05, Para, ObjGmCell, ...
        ApparatusBus, ApparatusType, ApparatusPowerFlow, Ts, ...
        ListBusNew, Advance, ObjZbusDss, NumBus, networkMatrix);
    highPoint = evaluateDamping(0.5, Para, ObjGmCell, ...
        ApparatusBus, ApparatusType, ApparatusPowerFlow, Ts, ...
        ListBusNew, Advance, ObjZbusDss, NumBus, networkMatrix);

    if ~isfolder(outputRoot)
        mkdir(outputRoot);
    end
    sweepTable = table(dampingGrid, maximumRealPoleHz, ...
        dominantPoleOscillationHz, dominantReturnZeroRealHz, ...
        dominantReturnZeroOscillationHz, ...
        'VariableNames', {'damping_D', 'dominant_pole_real_Hz', ...
        'dominant_pole_oscillation_Hz', 'dominant_return_zero_real_Hz', ...
        'dominant_return_zero_oscillation_Hz'});
    writetable(sweepTable, fullfile(outputRoot, 'damping_sweep.csv'));

    summary = struct( ...
        'inputWorkbook', ...
            "external/cifelli-small-gain-phase/" + string(inputName), ...
        'variedWorkbookCell', 'Apparatus!I39', ...
        'variedStructField', 'Para{2}.Dw', ...
        'variedModelParameter', 'obj.Para(7) = VSM damping D', ...
        'fixedNetworkRpu', UserDataStruct.NetworkLine(1).R, ...
        'fixedNetworkWLpu', UserDataStruct.NetworkLine(1).wL, ...
        'fixedBusGenerationPpu', UserDataStruct.Bus(2).PGi, ...
        'fixedBusLoadPpu', UserDataStruct.Bus(2).PLi, ...
        'fixedInertiaH', Para{2}.fdroop, ...
        'fixedQControlEnable', Para{2}.fvdq, ...
        'criticalDamping', criticalDamping, ...
        'criticalPoleRealHz', real(criticalPoint.dominantPoleHz), ...
        'criticalOscillationHz', abs(imag(criticalPoint.dominantPoleHz)), ...
        'criticalReturnZeroRealHz', real(criticalPoint.dominantReturnZeroHz), ...
        'criticalReturnZeroOscillationHz', ...
            abs(imag(criticalPoint.dominantReturnZeroHz)), ...
        'poleZeroMismatchHz', abs(criticalPoint.dominantPoleHz - ...
            criticalPoint.dominantReturnZeroHz), ...
        'damping005PoleRealHz', real(lowPoint.dominantPoleHz), ...
        'damping005OscillationHz', abs(imag(lowPoint.dominantPoleHz)), ...
        'damping05PoleRealHz', real(highPoint.dominantPoleHz), ...
        'damping05OscillationHz', abs(imag(highPoint.dominantPoleHz)), ...
        'stableAtDamping005', real(lowPoint.dominantPoleHz) <= 0, ...
        'stableAtDamping05', real(highPoint.dominantPoleHz) <= 0);
    writelines(jsonencode(summary, PrettyPrint=true), ...
        fullfile(outputRoot, 'summary.json'));
    save(fullfile(outputRoot, 'damping_continuation_workspace.mat'), ...
        'dampingGrid', 'maximumRealPoleHz', 'dominantPoleOscillationHz', ...
        'dominantReturnZeroRealHz', 'dominantReturnZeroOscillationHz', ...
        'criticalDamping', 'criticalPoint', 'summary');

    fprintf(['DAMPING_CRITICAL D=%.12g pole=%.12g+j%.12g Hz ', ...
        'return_zero=%.12g+j%.12g Hz mismatch=%.3g Hz\n'], ...
        criticalDamping, real(criticalPoint.dominantPoleHz), ...
        abs(imag(criticalPoint.dominantPoleHz)), ...
        real(criticalPoint.dominantReturnZeroHz), ...
        abs(imag(criticalPoint.dominantReturnZeroHz)), ...
        summary.poleZeroMismatchHz);
end

function point = evaluateDamping(damping, paraTemplate, objectTemplate, ...
        apparatusBus, apparatusType, apparatusPowerFlow, sampleTime, ...
        listBus, advance, objectZbus, numberOfBuses, networkMatrix)

    converterIndex = 2;
    para = paraTemplate{converterIndex};
    para.Dw = damping;
    [converterObject, converterDss] = ...
        SimplusGT.Toolbox.ApparatusModelCreate( ...
        apparatusBus{converterIndex}, apparatusType{converterIndex}, ...
        apparatusPowerFlow{converterIndex}, para, sampleTime, listBus, advance);

    objects = objectTemplate;
    objects{converterIndex} = converterObject;
    linkedObject = SimplusGT.Toolbox.ApparatusModelLink(objects);
    [systemDssObject, systemDss] = SimplusGT.Toolbox.ConnectGmZbus( ...
        linkedObject, objectZbus, numberOfBuses);
    assert(isproper(systemDss), 'DampingContinuation:ImproperSystem', ...
        'The closed-loop descriptor model is improper at D = %.12g.', damping);
    systemSsObject = SimplusGT.ObjDss2Ss(systemDssObject);
    [~, systemSs] = systemSsObject.GetSS(systemSsObject);

    polesHz = eig(systemSs.A) / (2*pi);
    dynamicPolesHz = polesHz(abs(polesHz) > 1e-7);
    [~, dominantPoleIndex] = max(real(dynamicPolesHz));
    dominantPoleHz = dynamicPolesHz(dominantPoleIndex);

    converterMatrix = minreal(converterDss(1:2, 1:2));
    returnZerosHz = tzero(ss(minreal(networkMatrix + converterMatrix))) / (2*pi);
    dynamicReturnZerosHz = returnZerosHz(abs(returnZerosHz) > 1e-7);
    [~, dominantZeroIndex] = max(real(dynamicReturnZerosHz));
    dominantReturnZeroHz = dynamicReturnZerosHz(dominantZeroIndex);

    point = struct('damping', damping, ...
        'dominantPoleHz', dominantPoleHz, ...
        'dominantReturnZeroHz', dominantReturnZeroHz);
end

function prepareRuntimeTool(simplusRoot, authorRoot, runtimeRoot, inputName)
    if isfolder(runtimeRoot)
        rmdir(runtimeRoot, 's');
    end
    [copyStatus, copyMessage] = copyfile(simplusRoot, runtimeRoot);
    assert(copyStatus, 'DampingContinuation:CopySimplusFailed', '%s', copyMessage);
    [copyStatus, copyMessage] = copyfile( ...
        fullfile(authorRoot, 'GridFormingVSI.m'), ...
        fullfile(runtimeRoot, '+SimplusGT', '+Class', 'GridFormingVSI.m'), 'f');
    assert(copyStatus, 'DampingContinuation:CopyClassFailed', '%s', copyMessage);
    [copyStatus, copyMessage] = copyfile( ...
        fullfile(authorRoot, inputName), fullfile(runtimeRoot, 'UserData.xlsm'), 'f');
    assert(copyStatus, 'DampingContinuation:CopyInputFailed', '%s', copyMessage);
    jsonPath = fullfile(runtimeRoot, 'UserData.json');
    if isfile(jsonPath)
        delete(jsonPath);
    end
end

function rmpathIfPresent(pathText)
    pathParts = split(string(pathText), pathsep);
    activeParts = split(string(path), pathsep);
    removableParts = pathParts(ismember(lower(pathParts), lower(activeParts)));
    if ~isempty(removableParts)
        rmpath(char(join(removableParts, pathsep)));
    end
end

function restoreEnvironment(oldPath, oldFolder, oldFigureVisibility, runtimeRoot)
    path(oldPath);
    cd(oldFolder);
    set(groot, 'defaultFigureVisible', oldFigureVisibility);
    close all force;
    if isfolder(runtimeRoot)
        rmdir(runtimeRoot, 's');
    end
end
