function summary = run_inf_bus_schur_analysis(caseName)
%RUN_INF_BUS_SCHUR_ANALYSIS Analyze the paper baseline by Schur reduction.
%   SUMMARY = RUN_INF_BUS_SCHUR_ANALYSIS(CASENAME) loads the corresponding
%   isolated infinite-bus baseline, applies the static power-polar paired
%   transformation, and factors the total 2-by-2 characteristic matrix
%   into its voltage block and effective angle Schur complement.

    arguments
        caseName (1, 1) string {mustBeMember(caseName, ["stable", "unstable"])}
    end

    projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
    addpath(fullfile(projectRoot, 'src'), '-begin');
    baselinePath = fullfile(projectRoot, 'results', 'baseline', caseName, ...
        'baseline_workspace.mat');
    outputRoot = fullfile(projectRoot, 'results', 'schur', caseName);
    assert(isfile(baselinePath), 'SchurAnalysis:MissingBaseline', ...
        'Run the corresponding infinite-bus baseline first.');

    data = load(baselinePath);
    requiredFields = ["Yc", "Ynet", "GsysSs", "powerFlow"];
    assert(all(isfield(data, requiredFields)), ...
        'SchurAnalysis:OutdatedBaseline', ...
        'The baseline workspace must be regenerated with operating-point data.');

    powerFlow = data.powerFlow;
    voltageMagnitude = powerFlow(3);
    voltageAngle = powerFlow(4);
    voltage = voltageMagnitude * exp(1i * voltageAngle);
    activePower = powerFlow(1);
    reactivePower = powerFlow(2);
    current = (activePower - 1i * reactivePower) / conj(voltage);
    vd0 = real(voltage);
    vq0 = imag(voltage);
    id0 = real(current);
    iq0 = imag(current);

    outputTransform = [vd0, vq0; vq0, -vd0];
    inputTransform = [-vq0, vd0; vd0, vq0];
    translation = [id0, iq0; -iq0, id0];

    converterMatrix = minreal( ...
        (outputTransform * data.Yc + translation) * inputTransform);
    networkMatrix = minreal( ...
        (outputTransform * data.Ynet - translation) * inputTransform);
    totalMatrix = minreal(converterMatrix + networkMatrix);
    voltagePivotParts = decomposeAngleVoltageSchur(totalMatrix, Pivot="voltage");
    anglePivotParts = decomposeAngleVoltageSchur(totalMatrix, Pivot="angle");

    frequenciesHz = logspace(log10(1e-3), log10(1e4), 2000).';
    normalizedVoltageMargin = zeros(size(frequenciesHz));
    normalizedAngleMargin = zeros(size(frequenciesHz));
    normalizedAnglePivotMargin = zeros(size(frequenciesHz));
    normalizedVoltageSchurMargin = zeros(size(frequenciesHz));
    normalizedTotalMargin = zeros(size(frequenciesHz));
    relativeFactorizationResidual = zeros(size(frequenciesHz));

    for index = 1:numel(frequenciesHz)
        matrixAtFrequency = evalfr(totalMatrix, 1i * 2*pi*frequenciesHz(index));
        partsAtFrequency = decomposeAngleVoltageSchur(matrixAtFrequency);
        reversePartsAtFrequency = decomposeAngleVoltageSchur( ...
            matrixAtFrequency, Pivot="angle");
        matrixScale = max(norm(matrixAtFrequency, 2), eps);
        normalizedVoltageMargin(index) = ...
            abs(partsAtFrequency.voltageBlock) / matrixScale;
        normalizedAngleMargin(index) = ...
            abs(partsAtFrequency.schurComplement) / matrixScale;
        normalizedAnglePivotMargin(index) = ...
            abs(reversePartsAtFrequency.pivotBlock) / matrixScale;
        normalizedVoltageSchurMargin(index) = ...
            abs(reversePartsAtFrequency.schurComplement) / matrixScale;
        normalizedTotalMargin(index) = ...
            min(svd(matrixAtFrequency)) / matrixScale;
        relativeFactorizationResidual(index) = ...
            abs(partsAtFrequency.factorizationResidual) / ...
            max(1, abs(partsAtFrequency.characteristicDeterminant));
    end

    voltageZerosHz = tzero(ss(voltagePivotParts.pivotBlock)) / (2*pi);
    anglePivotZerosHz = tzero(ss(anglePivotParts.pivotBlock)) / (2*pi);
    totalZerosHz = tzero(ss(totalMatrix)) / (2*pi);
    closedLoopPolesHz = eig(data.GsysSs.A) / (2*pi);

    [minimumVoltageMargin, voltageMarginIndex] = min(normalizedVoltageMargin);
    [minimumAngleMargin, angleMarginIndex] = min(normalizedAngleMargin);
    [minimumTotalMargin, totalMarginIndex] = min(normalizedTotalMargin);

    summary = struct( ...
        'caseName', caseName, ...
        'minimumNormalizedVoltageMargin', minimumVoltageMargin, ...
        'minimumVoltageMarginHz', frequenciesHz(voltageMarginIndex), ...
        'minimumNormalizedAngleMargin', minimumAngleMargin, ...
        'minimumAngleMarginHz', frequenciesHz(angleMarginIndex), ...
        'minimumNormalizedTotalMargin', minimumTotalMargin, ...
        'minimumTotalMarginHz', frequenciesHz(totalMarginIndex), ...
        'maximumFactorizationResidual', max(relativeFactorizationResidual), ...
        'maximumRealVoltageZeroHz', maximumRealPart(voltageZerosHz), ...
        'maximumRealAnglePivotZeroHz', maximumRealPart(anglePivotZerosHz), ...
        'maximumRealTotalZeroHz', maximumRealPart(totalZerosHz), ...
        'maximumRealClosedLoopPoleHz', max(real(closedLoopPolesHz)), ...
        'hasUnstableVoltageZero', any(real(voltageZerosHz) > 1e-6), ...
        'hasUnstableAnglePivotZero', any(real(anglePivotZerosHz) > 1e-6), ...
        'hasUnstableTotalZero', any(real(totalZerosHz) > 1e-6));

    if ~isfolder(outputRoot)
        mkdir(outputRoot);
    end
    marginTable = table( ...
        frequenciesHz, normalizedVoltageMargin, normalizedAngleMargin, ...
        normalizedAnglePivotMargin, normalizedVoltageSchurMargin, ...
        normalizedTotalMargin, relativeFactorizationResidual, ...
        'VariableNames', {'frequency_Hz', 'normalized_voltage_margin', ...
        'normalized_angle_schur_margin', 'normalized_angle_pivot_margin', ...
        'normalized_voltage_schur_margin', 'normalized_total_sigma_min', ...
        'relative_factorization_residual'});
    writetable(marginTable, fullfile(outputRoot, 'frequency_margins.csv'));
    writelines(jsonencode(summary, PrettyPrint=true), ...
        fullfile(outputRoot, 'summary.json'));
    save(fullfile(outputRoot, 'schur_workspace.mat'), ...
        'converterMatrix', 'networkMatrix', 'totalMatrix', ...
        'voltagePivotParts', 'anglePivotParts', ...
        'voltageZerosHz', 'anglePivotZerosHz', 'totalZerosHz', ...
        'closedLoopPolesHz', 'summary');

    fprintf(['SCHUR case=%s min_voltage=%.6g@%.6gHz ', ...
        'min_angle=%.6g@%.6gHz min_total=%.6g@%.6gHz ', ...
        'RHP_zeros=[D:%d A:%d total:%d]\n'], ...
        caseName, minimumVoltageMargin, frequenciesHz(voltageMarginIndex), ...
        minimumAngleMargin, frequenciesHz(angleMarginIndex), ...
        minimumTotalMargin, frequenciesHz(totalMarginIndex), ...
        summary.hasUnstableVoltageZero, summary.hasUnstableAnglePivotZero, ...
        summary.hasUnstableTotalZero);
end

function value = maximumRealPart(numbers)
    if isempty(numbers)
        value = -Inf;
    else
        value = max(real(numbers));
    end
end
