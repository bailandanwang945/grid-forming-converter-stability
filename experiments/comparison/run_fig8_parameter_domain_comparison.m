function summary = run_fig8_parameter_domain_comparison(options)
%RUN_FIG8_PARAMETER_DOMAIN_COMPARISON Compare two stability assessments.
%   On one author Fig. 8 model and one (D,kappa) parameter grid, this
%   experiment records both the closed-loop eigenvalue reference and the
%   conditional finite-frequency mixed gain/phase screening result.
%
%   The screening result is not a theorem-level conclusion: the frequency
%   range is finite, phase unwrapping uses a declared nearest-neighbour
%   branch assumption, and the theorem preconditions are only declared,
%   not established by this experiment. A point not covered by the
%   sufficient condition may nevertheless be closed-loop stable.

    if nargin < 1
        options = struct();
    end
    options = validateOptions(options);

    projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
    authorRoot = fullfile(projectRoot, 'external', ...
        'cifelli-small-gain-phase');
    simplusRoot = fullfile(projectRoot, 'external', 'simplus-grid-tool');
    runtimeParent = fullfile(projectRoot, 'tmp', ...
        'fig8-domain-comparison');
    if ~isfolder(runtimeParent)
        mkdir(runtimeParent);
    end
    runtimeRoot = tempname(runtimeParent);
    outputRoot = fullfile(projectRoot, 'results', 'comparison', ...
        'fig8-damping-grid-strength');
    inputName = 'UserData_inf_bus_Fig_8.xlsm';

    oldPath = path;
    oldFolder = pwd;
    oldFigureVisibility = get(groot, 'defaultFigureVisible');
    cleanup = onCleanup(@() restoreEnvironment( ...
        oldPath, oldFolder, oldFigureVisibility, runtimeRoot)); %#ok<NASGU>

    prepareRuntimeTool(simplusRoot, authorRoot, runtimeRoot, inputName);
    path(oldPath);
    rmpathIfPresent(genpath(simplusRoot));
    addpath(genpath(runtimeRoot), '-begin');
    addpath(authorRoot, '-begin');
    addpath(fullfile(projectRoot, 'src'), '-begin');
    addpath(fullfile(projectRoot, 'experiments', 'baseline'), '-begin');
    set(groot, 'defaultFigureVisible', 'off');
    cd(runtimeRoot);
    rehash;

    resolvedClass = which('SimplusGT.Class.GridFormingVSI');
    expectedClass = fullfile(runtimeRoot, '+SimplusGT', '+Class', ...
        'GridFormingVSI.m');
    assert(strcmpi(resolvedClass, expectedClass), ...
        'Fig8Domain:WrongClass', ...
        'The isolated author GridFormingVSI class was not resolved.');

    UserDataName = 'UserData'; %#ok<NASGU>
    UserDataType = 1; %#ok<NASGU>
    NumApparatus = NaN; %#ok<NASGU>
    ApparatusType = {}; %#ok<NASGU>
    Para = {}; %#ok<NASGU>
    SimplusGT.Toolbox.Main();
    assert(NumApparatus == 2 && ApparatusType{2} == 20, ...
        'Fig8Domain:UnexpectedSystem', ...
        'The workbook is not the expected GFM-infinite-bus system.');

    base = struct( ...
        'listBus', ListBus, ...
        'listLine', ListLine, ...
        'wbase', Wbase, ...
        'sampleTime', Ts, ...
        'advance', Advance, ...
        'apparatusBus', {ApparatusBus}, ...
        'apparatusType', {ApparatusType}, ...
        'para', {Para}, ...
        'numberOfBuses', NumBus);
    mutualRows = base.listLine(:, 1) ~= base.listLine(:, 2);
    baseLineR = base.listLine(mutualRows, 3);
    baseLineWL = base.listLine(mutualRows, 4);
    assert(isscalar(baseLineR) && isscalar(baseLineWL), ...
        'Fig8Domain:UnexpectedNetwork', ...
        'The experiment requires the one-line infinite-bus case.');

    frequenciesHz = options.FrequenciesHz;
    weighting = buildVirtualImpedanceWeightingSamples(frequenciesHz, ...
        struct('BaseAngularFrequency', base.wbase, ...
        'VirtualResistance', 0.01, 'VirtualReactance', 0.1, ...
        'NormalizeAtBase', true));
    transformationMetadata = authorTransformationMetadata();
    evaluatorConventions = authorEvaluatorConventions(base.wbase);
    preconditions = declaredPreconditions();
    if ~isfolder(outputRoot)
        mkdir(outputRoot);
    end
    progressPath = fullfile(outputRoot, 'progress.json');

    rowCount = numel(options.KappaGrid) * numel(options.DampingGrid);
    rows = initializeRows(rowCount);
    anchor = initializeAnchorEvidence();
    rowIndex = 0;
    for kappaIndex = 1:numel(options.KappaGrid)
        kappa = options.KappaGrid(kappaIndex);
        context = createContext(base, kappa);
        networkResponse = evaluateResponse( ...
            context.networkMatrix, frequenciesHz);
        operatingPoint = powerFlowToOperatingPoint( ...
            context.apparatusPowerFlow{2});
        scr = 1/(kappa*hypot(baseLineR, baseLineWL));

        for dampingIndex = 1:numel(options.DampingGrid)
            damping = options.DampingGrid(dampingIndex);
            rowIndex = rowIndex + 1;
            point = evaluateClosedLoopPoint(context, damping);
            converterResponse = evaluateResponse( ...
                point.converterDss(1:2, 1:2), frequenciesHz);
            shaping = buildMixedLoopShapingSamples( ...
                {converterResponse}, networkResponse, frequenciesHz, ...
                {operatingPoint}, {weighting.responses}, struct( ...
                'ConventionMetadata', transformationMetadata));
            screening = screenShapedResponses(shaping, frequenciesHz, ...
                evaluatorConventions, preconditions, ...
                options.PhaseClassifierAngles);

            [closedLoopStatus, maximumRealPoleHz, dominantFrequencyHz] = ...
                classifyClosedLoop(point.polesHz, options.PoleToleranceHz);
            counts = coverageCounts(screening);
            classification = combineAssessment(closedLoopStatus, ...
                screening.sampledBandStatus, counts.indeterminate, ...
                shaping.transformationStatus);
            if classification == "consistency-violation"
                error('Fig8Domain:ConsistencyViolation', ...
                    ['Finite-grid criterion coverage occurred at a point ', ...
                    'whose closed-loop reference is unstable ', ...
                    '(kappa=%.6g, D=%.6g).'], kappa, damping);
            end

            rows.impedance_scale_kappa(rowIndex) = kappa;
            rows.SCR(rowIndex) = scr;
            rows.damping_D(rowIndex) = damping;
            rows.maximum_real_pole_Hz(rowIndex) = maximumRealPoleHz;
            rows.dominant_oscillation_frequency_Hz(rowIndex) = ...
                dominantFrequencyHz;
            rows.closed_loop_reference(rowIndex) = closedLoopStatus;
            rows.sampled_criterion_status(rowIndex) = ...
                string(screening.sampledBandStatus);
            rows.final_classification(rowIndex) = classification;
            rows.gain_pass_count(rowIndex) = ...
                nnz(screening.gainStatus == "pass");
            rows.gain_fail_count(rowIndex) = ...
                nnz(screening.gainStatus == "fail");
            rows.gain_indeterminate_count(rowIndex) = ...
                nnz(screening.gainStatus == "indeterminate");
            rows.phase_pass_count(rowIndex) = ...
                nnz(screening.phaseStatus == "pass");
            rows.phase_fail_count(rowIndex) = ...
                nnz(screening.phaseStatus == "fail");
            rows.phase_indeterminate_count(rowIndex) = ...
                nnz(screening.phaseStatus == "indeterminate");
            rows.uncovered_frequency_count(rowIndex) = counts.uncovered;
            rows.indeterminate_frequency_count(rowIndex) = ...
                counts.indeterminate;
            rows.converter_phase_seed_frequency_Hz(rowIndex) = ...
                frequenciesHz(screening.options.PhaseBranchOptions. ...
                SeedFrequencyIndices(1));
            rows.network_phase_seed_frequency_Hz(rowIndex) = ...
                frequenciesHz(screening.options.PhaseBranchOptions. ...
                SeedFrequencyIndices(2));
            rows.maximum_transformation_condition(rowIndex) = ...
                max(shaping.transformationConditionNumbers(:));
            rows.maximum_interconnection_residual(rowIndex) = ...
                max(shaping.interconnectionResidual);

            anchor = updateAnchorEvidence(anchor, kappa, damping, ...
                converterResponse, networkResponse, maximumRealPoleHz, ...
                frequenciesHz, projectRoot);
            fprintf(['FIG8_DOMAIN %d/%d kappa=%.2f SCR=%.5f D=%.3f ', ...
                'pole=%+.6gHz criterion=%s class=%s\n'], ...
                rowIndex, rowCount, kappa, scr, damping, ...
                maximumRealPoleHz, screening.sampledBandStatus, ...
                classification);
            progress = struct('status', "running", ...
                'completedPoints', rowIndex, 'totalPoints', rowCount, ...
                'lastKappa', kappa, 'lastDamping', damping, ...
                'lastClassification', classification, ...
                'updatedAt', string(datetime('now', ...
                'Format', 'yyyy-MM-dd HH:mm:ss')));
            writelines(jsonencode(progress, PrettyPrint=true), progressPath);
        end
    end

    resultTable = struct2table(rows);
    counts = classificationCounts(resultTable.final_classification);
    assert(counts.consistencyViolation == 0, ...
        'Fig8Domain:ConsistencyViolation', ...
        'Criterion-covered points must be inside the reference stable set.');
    if options.VerifyAnchors
        verifyAnchorEvidence(anchor);
    end

    writetable(resultTable, fullfile(outputRoot, 'parameter_domain.csv'));
    summary = struct( ...
        'schemaVersion', "1.0.0", ...
        'method', "author-fig8-same-domain-comparison-v1", ...
        'sourceWorkbook', ...
            "external/cifelli-small-gain-phase/" + string(inputName), ...
        'parameterPointCount', height(resultTable), ...
        'frequencyPointCountPerParameterPoint', numel(frequenciesHz), ...
        'frequencyMinimumHz', frequenciesHz(1), ...
        'frequencyMaximumHz', frequenciesHz(end), ...
        'phaseClassifierAngles', options.PhaseClassifierAngles, ...
        'kappaGrid', options.KappaGrid, ...
        'dampingGrid', options.DampingGrid, ...
        'scrMinimum', min(resultTable.SCR), ...
        'scrMaximum', max(resultTable.SCR), ...
        'classificationCounts', counts, ...
        'criterionCoveredSubsetOfReferenceStable', ...
            counts.consistencyViolation == 0, ...
        'anchorEvidence', anchor, ...
        'screeningBoundary', [ ...
            "Conditional finite-frequency screening only; " + ...
            "not a theorem-level conclusion. Phase coverage depends on " + ...
            "a declared nearest-neighbour branch assumption."], ...
        'interpretation', [ ...
            "stable-not-covered quantifies observed conservatism of this " + ...
            "sufficient-condition screening on the pinned model and grid; " + ...
            "it does not invalidate the theorem."], ...
        'closedLoopBoundary', [ ...
            "Finite-precision eigenvalue reference for the pinned " + ...
            "author model; not physical ground truth."]);
    writelines(jsonencode(summary, PrettyPrint=true), ...
        fullfile(outputRoot, 'summary.json'));
    progress = struct('status', "complete", ...
        'completedPoints', height(resultTable), ...
        'totalPoints', height(resultTable), ...
        'updatedAt', string(datetime('now', ...
        'Format', 'yyyy-MM-dd HH:mm:ss')));
    writelines(jsonencode(progress, PrettyPrint=true), progressPath);
    fprintf(['FIG8_DOMAIN_DONE points=%d covered_stable=%d ', ...
        'stable_not_covered=%d unstable=%d pending=%d\n'], ...
        height(resultTable), counts.criterionCoveredStable, ...
        counts.stableNotCovered, counts.unstableNotCovered, ...
        counts.numericalPending);
end

function options = validateOptions(options)
    defaults = struct( ...
        'KappaGrid', (0.5:0.1:1.5).', ...
        'DampingGrid', unique([0.04, 0.05, 0.06:0.02:0.20, ...
            0.25:0.05:0.50]).', ...
        'FrequenciesHz', canonicalSweepFrequencies(), ...
        'PhaseClassifierAngles', 90, ...
        'PoleToleranceHz', 1e-8, ...
        'VerifyAnchors', true);
    assert(isstruct(options) && isscalar(options), ...
        'Fig8Domain:InvalidOptions', 'options must be a scalar struct.');
    unknown = setdiff(fieldnames(options), fieldnames(defaults));
    assert(isempty(unknown), 'Fig8Domain:UnknownOption', ...
        'Unknown option: %s.', firstOrEmpty(unknown));
    names = fieldnames(defaults);
    for index = 1:numel(names)
        if ~isfield(options, names{index})
            options.(names{index}) = defaults.(names{index});
        end
    end
    validateGrid(options.KappaGrid, 'KappaGrid');
    validateGrid(options.DampingGrid, 'DampingGrid');
    validateGrid(options.FrequenciesHz, 'FrequenciesHz');
    options.KappaGrid = options.KappaGrid(:);
    options.DampingGrid = options.DampingGrid(:);
    options.FrequenciesHz = options.FrequenciesHz(:);
    assert(options.FrequenciesHz(1) > 0, ...
        'Fig8Domain:InvalidFrequencies', ...
        'FrequenciesHz must be strictly positive.');
    assert(isnumeric(options.PoleToleranceHz) && ...
        isscalar(options.PoleToleranceHz) && ...
        isfinite(options.PoleToleranceHz) && options.PoleToleranceHz > 0, ...
        'Fig8Domain:InvalidPoleTolerance', ...
        'PoleToleranceHz must be finite and positive.');
    assert(isnumeric(options.PhaseClassifierAngles) && ...
        isscalar(options.PhaseClassifierAngles) && ...
        isfinite(options.PhaseClassifierAngles) && ...
        options.PhaseClassifierAngles >= 16 && ...
        fix(options.PhaseClassifierAngles) == options.PhaseClassifierAngles, ...
        'Fig8Domain:InvalidPhaseClassifierAngles', ...
        'PhaseClassifierAngles must be an integer of at least 16.');
    assert(islogical(options.VerifyAnchors) && isscalar(options.VerifyAnchors), ...
        'Fig8Domain:InvalidVerifyAnchors', ...
        'VerifyAnchors must be a logical scalar.');
    if options.VerifyAnchors
        assert(any(abs(options.KappaGrid-1) <= 1e-12) && ...
            any(abs(options.DampingGrid-0.05) <= 1e-12) && ...
            any(abs(options.DampingGrid-0.5) <= 1e-12) && ...
            all(ismember(options.FrequenciesHz, ...
                logspace(-3, 4, 1000).')), ...
            'Fig8Domain:MissingAnchors', ...
            'Canonical anchors require kappa=1, D=0.05/0.5 and the 1000-point grid.');
    end
end

function frequencies = canonicalSweepFrequencies()
    fullGrid = logspace(-3, 4, 1000).';
    indices = unique(round(linspace(1, numel(fullGrid), 121))).';
    frequencies = fullGrid(indices);
end

function validateGrid(values, name)
    assert(isnumeric(values) && isreal(values) && isvector(values) && ...
        ~isempty(values) && all(isfinite(values)) && all(values > 0) && ...
        all(diff(values(:)) > 0), 'Fig8Domain:InvalidGrid', ...
        '%s must be finite, positive, and strictly increasing.', name);
end

function value = firstOrEmpty(values)
    if isempty(values), value = ''; else, value = values{1}; end
end

