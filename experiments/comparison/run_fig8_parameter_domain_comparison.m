function [status, maximumRealPoleHz, dominantFrequencyHz] = ...
        classifyClosedLoop(polesHz, toleranceHz)
    assert(~isempty(polesHz) && all(isfinite(polesHz)), ...
        'Fig8Domain:InvalidPoles', 'Closed-loop poles must be finite.');
    [maximumRealPoleHz, index] = max(real(polesHz));
    dominantFrequencyHz = abs(imag(polesHz(index)));
    if maximumRealPoleHz > toleranceHz
        status = "unstable";
    elseif maximumRealPoleHz < -toleranceHz
        status = "stable";
    else
        status = "marginal";
    end
end

function counts = coverageCounts(screening)
    counts = struct( ...
        'uncovered', nnz(screening.sampleCoverage == "uncovered"), ...
        'indeterminate', nnz(screening.sampleCoverage == "indeterminate"));
end

function classification = combineAssessment(closedLoopStatus, ...
        sampledBandStatus, indeterminateCount, transformationStatus)
    transformationPending = any( ...
        transformationStatus ~= "sampled-algebra-resolved");
    criterionCovered = any(string(sampledBandStatus) == [ ...
        "gain-covered-on-grid", ...
        "covered-on-grid-under-phase-branch-assumption"]);
    if closedLoopStatus == "marginal" || indeterminateCount > 0 || ...
            transformationPending || sampledBandStatus == "indeterminate"
        classification = "numerical-pending";
    elseif criterionCovered && closedLoopStatus == "stable"
        classification = "criterion-covered-stable";
    elseif criterionCovered
        classification = "consistency-violation";
    elseif closedLoopStatus == "stable"
        classification = "stable-not-covered";
    else
        classification = "unstable-not-covered";
    end
end

function counts = classificationCounts(classification)
    counts = struct( ...
        'criterionCoveredStable', ...
            nnz(classification == "criterion-covered-stable"), ...
        'stableNotCovered', nnz(classification == "stable-not-covered"), ...
        'unstableNotCovered', ...
            nnz(classification == "unstable-not-covered"), ...
        'numericalPending', nnz(classification == "numerical-pending"), ...
        'consistencyViolation', ...
            nnz(classification == "consistency-violation"));
end

function anchor = initializeAnchorEvidence()
    anchor = struct( ...
        'damping005ConverterMaxAbsError', NaN, ...
        'damping005NetworkMaxAbsError', NaN, ...
        'damping005MaximumRealPoleErrorHz', NaN, ...
        'damping05ConverterMaxAbsError', NaN, ...
        'damping05NetworkMaxAbsError', NaN, ...
        'damping05MaximumRealPoleErrorHz', NaN);
end

function anchor = updateAnchorEvidence(anchor, kappa, damping, ...
        converterResponse, networkResponse, maximumRealPoleHz, ...
        frequenciesHz, projectRoot)
    if abs(kappa-1) > 1e-12 || ...
            ~(abs(damping-0.05) <= 1e-12 || abs(damping-0.5) <= 1e-12)
        return;
    end
    fixture = load_author_fig8_raw_fixture(fullfile(projectRoot, ...
        'experiments', 'baseline', 'fixtures'));
    fixtureIndex = find(abs([fixture.cases.damping]-damping) <= 1e-12, 1);
    fixtureCase = fixture.cases(fixtureIndex);
    [isFixtureFrequency, fixtureIndices] = ismember( ...
        frequenciesHz, fixtureCase.frequenciesHz(:));
    assert(all(isFixtureFrequency), 'Fig8Domain:AnchorFrequencyMismatch', ...
        'Every sweep frequency must be an exact pinned-fixture frequency.');
    poleRows = fixtureCase.spectrum( ...
        fixtureCase.spectrum.value_type == "closed-loop-pole", :);
    poleError = abs(maximumRealPoleHz-max(poleRows.real_Hz));
    converterError = max(abs( ...
        converterResponse(:)-reshape(fixtureCase.converterResponse( ...
        :, :, fixtureIndices), [], 1)));
    networkError = max(abs( ...
        networkResponse(:)-reshape(fixtureCase.networkResponse( ...
        :, :, fixtureIndices), [], 1)));
    if abs(damping-0.05) <= 1e-12
        anchor.damping005ConverterMaxAbsError = converterError;
        anchor.damping005NetworkMaxAbsError = networkError;
        anchor.damping005MaximumRealPoleErrorHz = poleError;
    else
        anchor.damping05ConverterMaxAbsError = converterError;
        anchor.damping05NetworkMaxAbsError = networkError;
        anchor.damping05MaximumRealPoleErrorHz = poleError;
    end
end

function verifyAnchorEvidence(anchor)
    values = struct2array(anchor);
    assert(all(isfinite(values)), 'Fig8Domain:MissingAnchorEvidence', ...
        'Both kappa=1, D=0.05/0.5 anchors must be evaluated.');
    assert(anchor.damping005ConverterMaxAbsError <= 1e-9 && ...
        anchor.damping005NetworkMaxAbsError <= 1e-9 && ...
        anchor.damping005MaximumRealPoleErrorHz <= 1e-8 && ...
        anchor.damping05ConverterMaxAbsError <= 1e-9 && ...
        anchor.damping05NetworkMaxAbsError <= 1e-9 && ...
        anchor.damping05MaximumRealPoleErrorHz <= 1e-8, ...
        'Fig8Domain:AnchorMismatch', ...
        'Same-domain generation does not match the pinned Fig. 8 fixtures.');
end

function prepareRuntimeTool(simplusRoot, authorRoot, runtimeRoot, inputName)
    assert(~isfolder(runtimeRoot), 'Fig8Domain:RuntimeAlreadyExists', ...
        'The isolated runtime path must be new.');
    [status, message] = copyfile(simplusRoot, runtimeRoot);
    assert(status, 'Fig8Domain:CopySimplusFailed', '%s', message);
    [status, message] = copyfile(fullfile(authorRoot, 'GridFormingVSI.m'), ...
        fullfile(runtimeRoot, '+SimplusGT', '+Class', ...
        'GridFormingVSI.m'), 'f');
    assert(status, 'Fig8Domain:CopyClassFailed', '%s', message);
    [status, message] = copyfile(fullfile(authorRoot, inputName), ...
        fullfile(runtimeRoot, 'UserData.xlsm'), 'f');
    assert(status, 'Fig8Domain:CopyInputFailed', '%s', message);
    jsonPath = fullfile(runtimeRoot, 'UserData.json');
    if isfile(jsonPath), delete(jsonPath); end
end

function rmpathIfPresent(pathText)
    pathParts = split(string(pathText), pathsep);
    activeParts = split(string(path), pathsep);
    removable = pathParts(ismember(lower(pathParts), lower(activeParts)));
    if ~isempty(removable), rmpath(char(join(removable, pathsep))); end
end

function restoreEnvironment(oldPath, oldFolder, visibility, runtimeRoot)
    path(oldPath);
    cd(oldFolder);
    set(groot, 'defaultFigureVisible', visibility);
    close all force;
    if isfolder(runtimeRoot)
        try
            rmdir(runtimeRoot, 's');
        catch cleanupError
            warning('Fig8Domain:RuntimeCleanupFailed', ...
                'Temporary runtime cleanup failed: %s', cleanupError.message);
        end
    end
end
