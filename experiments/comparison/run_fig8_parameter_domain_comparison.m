function context = createContext(base, kappa)
    listLine = base.listLine;
    mutualRows = listLine(:, 1) ~= listLine(:, 2);
    listLine(mutualRows, 3:4) = kappa*base.listLine(mutualRows, 3:4);
    switch base.advance.PowerFlowAlgorithm
        case 1
            powerFlow = SimplusGT.PowerFlow.PowerFlowGS( ...
                base.listBus, listLine, base.wbase);
        case 2
            powerFlow = SimplusGT.PowerFlow.PowerFlowNR( ...
                base.listBus, listLine, base.wbase);
        otherwise
            error('Fig8Domain:PowerFlowAlgorithm', ...
                'Unsupported power-flow algorithm.');
    end
    [listBusNew, listLineNew, powerFlowNew] = ...
        SimplusGT.PowerFlow.Load2SelfBranch( ...
        base.listBus, listLine, powerFlow);
    [objectYbus, ybusDss] = SimplusGT.Toolbox.YbusCalcDss( ...
        listBusNew, listLineNew, base.wbase);
    objectZbus = SimplusGT.ObjSwitchInOut(objectYbus, length(ybusDss));
    [~, networkMatrix] = objectYbus.GetDSS(objectYbus);
    networkMatrix = networkMatrix(3:end, 3:end);

    apparatusPowerFlow = cell(size(base.apparatusType));
    objectTemplate = cell(size(base.apparatusType));
    for apparatusIndex = 1:numel(base.apparatusType)
        bus = base.apparatusBus{apparatusIndex};
        apparatusPowerFlow{apparatusIndex} = powerFlowNew{bus};
        objectTemplate{apparatusIndex} = ...
            SimplusGT.Toolbox.ApparatusModelCreate( ...
            bus, base.apparatusType{apparatusIndex}, ...
            apparatusPowerFlow{apparatusIndex}, ...
            base.para{apparatusIndex}, base.sampleTime, ...
            listBusNew, base.advance);
    end
    context = struct('kappa', kappa, 'listBusNew', listBusNew, ...
        'networkMatrix', networkMatrix, 'objectZbus', objectZbus, ...
        'apparatusPowerFlow', {apparatusPowerFlow}, ...
        'objectTemplate', {objectTemplate}, 'base', base);
end

function point = evaluateClosedLoopPoint(context, damping)
    [converterObject, converterDss] = converterAt(context, damping);
    objects = context.objectTemplate;
    objects{2} = converterObject;
    linkedObject = SimplusGT.Toolbox.ApparatusModelLink(objects);
    [systemDssObject, systemDss] = SimplusGT.Toolbox.ConnectGmZbus( ...
        linkedObject, context.objectZbus, context.base.numberOfBuses);
    assert(isproper(systemDss), 'Fig8Domain:ImproperSystem', ...
        'The closed-loop descriptor model is improper.');
    systemSsObject = SimplusGT.ObjDss2Ss(systemDssObject);
    [~, systemSs] = systemSsObject.GetSS(systemSsObject);
    polesHz = eig(systemSs.A)/(2*pi);
    polesHz = polesHz(abs(polesHz) > 1e-7);
    point = struct('polesHz', polesHz, 'converterDss', converterDss);
end

function [converterObject, converterDss] = converterAt(context, damping)
    para = context.base.para{2};
    para.Dw = damping;
    [converterObject, converterDss] = ...
        SimplusGT.Toolbox.ApparatusModelCreate( ...
        context.base.apparatusBus{2}, context.base.apparatusType{2}, ...
        context.apparatusPowerFlow{2}, para, context.base.sampleTime, ...
        context.listBusNew, context.base.advance);
end

function response = evaluateResponse(model, frequenciesHz)
    response = complex(zeros(2, 2, numel(frequenciesHz)));
    for index = 1:numel(frequenciesHz)
        response(:, :, index) = evalfr( ...
            model, 1i*2*pi*frequenciesHz(index));
    end
end

function operatingPoint = powerFlowToOperatingPoint(powerFlow)
    powerFlow = powerFlow(:).';
    assert(numel(powerFlow) == 5 && all(isfinite(powerFlow)), ...
        'Fig8Domain:InvalidPowerFlow', ...
        'Power flow must be [P,Q,V,phi,omega].');
    voltage = powerFlow(3)*exp(1i*powerFlow(4));
    current = (powerFlow(1)-1i*powerFlow(2))/conj(voltage);
    operatingPoint = struct('vd', real(voltage), 'vq', imag(voltage), ...
        'id', real(current), 'iq', imag(current));
end

function screening = screenShapedResponses(shaping, frequenciesHz, ...
        conventions, preconditions, phaseClassifierAngles)
    phaseOptions = struct('ClassifierOptions', struct( ...
        'NumAngles', phaseClassifierAngles, 'RelTol', 1e-10, ...
        'AbsTol', 0, 'Refine', true));
    inverseNetwork = inverseResponse(shaping.networkResponse);
    [converterSeed, converterSeedIndex] = ...
        firstResolvedPhaseSeed(shaping.converterResponses{1}, phaseOptions);
    [networkSeed, networkSeedIndex] = ...
        firstResolvedPhaseSeed(inverseNetwork, phaseOptions);
    evaluatorOptions = struct( ...
        'PhaseCenterSeeds', struct( ...
            'converterCenters', converterSeed, ...
            'networkInverseCenter', networkSeed), ...
        'PhaseBranchOptions', struct('SeedFrequencyIndices', ...
            [converterSeedIndex; networkSeedIndex]), ...
        'PhaseOptions', phaseOptions, ...
        'PhaseSeedProvenance', ...
            "first-resolved-grid-point-principal-center");
    screening = evaluateMixedGainPhaseSamples( ...
        shaping.converterResponses, shaping.networkResponse, ...
        frequenciesHz, conventions, preconditions, evaluatorOptions);
end

function inverse = inverseResponse(response)
    inverse = complex(zeros(size(response)));
    identity = eye(size(response, 1));
    for index = 1:size(response, 3)
        inverse(:, :, index) = response(:, :, index)\identity;
    end
end

function [seed, seedIndex] = firstResolvedPhaseSeed(response, phaseOptions)
    for index = 1:size(response, 3)
        phase = computeStrictSectorialPhaseInterval( ...
            response(:, :, index), phaseOptions);
        if phase.status == "resolved"
            seed = phase.branchCenter;
            seedIndex = index;
            return;
        end
    end
    error('Fig8Domain:NoResolvedPhaseSeed', ...
        'No strict-sectorial sample is available for phase seeding.');
end

