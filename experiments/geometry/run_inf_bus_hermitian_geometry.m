function summary = run_inf_bus_hermitian_geometry()
%RUN_INF_BUS_HERMITIAN_GEOMETRY Diagnose pinned author frequency responses.
%   The tracked fixture contains two 2-by-2 converter frequency responses
%   derived from the author's stable and unstable infinite-bus baselines.
%   Those cases differ in several physical and control parameters. Their
%   comparison is descriptive and is not a single-parameter experiment.

    projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
    outputRoot = fullfile(projectRoot, 'results', 'geometry');
    sourceRoot = fullfile(projectRoot, 'src');
    fixturePath = fullfile(projectRoot, 'experiments', 'geometry', ...
        'fixtures', 'author_inf_bus_converter_frequency_response.csv');
    caseNames = ["stable", "unstable"];
    options = struct( ...
        'NumAngles', 1440, ...
        'RelTol', 1e-10, ...
        'MaxNormalizedEnvelopeGap', 5e-3);

    assert(isfile(fixturePath), 'Geometry:MissingFixture', ...
        'Tracked author frequency-response fixture is missing.');
    fixture = readtable(fixturePath, TextType='string');
    validateFixture(fixture, caseNames);

    oldPath = path;
    cleanup = onCleanup(@() path(oldPath));
    addpath(sourceRoot, '-begin');

    tables = cell(numel(caseNames), 1);
    for caseIndex = 1:numel(caseNames)
        caseName = caseNames(caseIndex);
        caseFixture = fixture(fixture.case_name == caseName, :);
        tables{caseIndex} = analyzeCase(caseFixture, options);
    end

    resultTable = vertcat(tables{:});
    if ~isfolder(outputRoot)
        mkdir(outputRoot);
    end
    csvPath = fullfile(outputRoot, 'baseline_hermitian_geometry.csv');
    writetable(resultTable, csvPath);

    stableRows = resultTable.case_name == "stable";
    unstableRows = resultTable.case_name == "unstable";
    summary = struct( ...
        'frequencyMinimumHz', min(resultTable.frequency_Hz), ...
        'frequencyMaximumHz', max(resultTable.frequency_Hz), ...
        'frequencyPointCountPerCase', sum(stableRows), ...
        'caseNames', caseNames, ...
        'stableMinimumNormalizedSeparationMargin', ...
            min(resultTable.normalized_separation_margin(stableRows)), ...
        'unstableMinimumNormalizedSeparationMargin', ...
            min(resultTable.normalized_separation_margin(unstableRows)), ...
        'stableStrictSectorialCount', sum(stableRows & ...
            resultTable.classification_status == "strict-sectorial"), ...
        'unstableStrictSectorialCount', sum(unstableRows & ...
            resultTable.classification_status == "strict-sectorial"), ...
        'classificationIndeterminateCount', sum( ...
            ~resultTable.classification_is_certified), ...
        'attributionPendingCount', sum( ...
            resultTable.attribution_status == "numerical-pending"), ...
        'overallNumericalPendingCount', sum( ...
            resultTable.overall_numerical_status == "numerical-pending"), ...
        'interpretationBoundary', ...
            ['H/G terms are algebraic contributions in one selected ', ...
             'critical direction, not physical causes or closed-loop ', ...
             'stability margins. Cases differ in damping, grid ', ...
             'impedance, operating point, and reactive-power control.']);
    writelines(jsonencode(summary, PrettyPrint=true), ...
        fullfile(outputRoot, 'summary.json'));

    fprintf(['HERMITIAN_GEOMETRY cases=%d points_per_case=%d ', ...
        'classification_pending=%d overall_pending=%d\n'], ...
        numel(caseNames), summary.frequencyPointCountPerCase, ...
        summary.classificationIndeterminateCount, ...
        summary.overallNumericalPendingCount);
end

function validateFixture(fixture, caseNames)
    requiredNames = ["case_name", "frequency_Hz", ...
        "Y11_real", "Y11_imag", "Y12_real", "Y12_imag", ...
        "Y21_real", "Y21_imag", "Y22_real", "Y22_imag"];
    assert(all(ismember(requiredNames, string(fixture.Properties.VariableNames))), ...
        'Geometry:InvalidFixtureColumns', ...
        'Frequency-response fixture does not contain all required columns.');
    assert(all(ismember(caseNames, unique(fixture.case_name))), ...
        'Geometry:InvalidFixtureCases', ...
        'Frequency-response fixture does not contain both pinned cases.');

    numericNames = requiredNames(2:end);
    for index = 1:numel(numericNames)
        assert(all(isfinite(fixture.(numericNames(index)))), ...
            'Geometry:NonFiniteFixture', ...
            'Frequency-response fixture contains NaN or Inf.');
    end

    expectedFrequencies = fixture.frequency_Hz( ...
        fixture.case_name == caseNames(1));
    for index = 2:numel(caseNames)
        actualFrequencies = fixture.frequency_Hz( ...
            fixture.case_name == caseNames(index));
        assert(isequal(actualFrequencies, expectedFrequencies), ...
            'Geometry:FrequencyGridMismatch', ...
            'Pinned cases must use the same ordered frequency grid.');
    end
end

function resultTable = analyzeCase(caseFixture, options)
    pointCount = height(caseFixture);
    normalizedMargin = zeros(pointCount, 1);
    normalizedLowerBound = zeros(pointCount, 1);
    normalizedUpperBound = zeros(pointCount, 1);
    theta = zeros(pointCount, 1);
    normalizedHermitianContribution = zeros(pointCount, 1);
    normalizedQuadratureContribution = zeros(pointCount, 1);
    normalizedCommutator = zeros(pointCount, 1);
    normalizedEigenvalueGap = zeros(pointCount, 1);
    directionDMagnitude = zeros(pointCount, 1);
    directionQMagnitude = zeros(pointCount, 1);
    directionQRelativePhase = zeros(pointCount, 1);
    classificationStatus = strings(pointCount, 1);
    classificationIsCertified = false(pointCount, 1);
    directionResolved = false(pointCount, 1);
    objectiveEnvelopeResolved = false(pointCount, 1);
    attributionStatus = strings(pointCount, 1);
    overallNumericalStatus = strings(pointCount, 1);

    for index = 1:pointCount
        matrix = matrixFromFixtureRow(caseFixture(index, :));
        diagnostic = analyzeHermitianGeometry(matrix, options);
        normalizedMargin(index) = diagnostic.normalizedSeparationMargin;
        normalizedLowerBound(index) = ...
            diagnostic.classification.normalizedLowerBound;
        normalizedUpperBound(index) = ...
            diagnostic.classification.normalizedUpperBound;
        theta(index) = diagnostic.theta;
        normalizedHermitianContribution(index) = ...
            diagnostic.normalizedHermitianContribution;
        normalizedQuadratureContribution(index) = ...
            diagnostic.normalizedQuadratureContribution;
        normalizedCommutator(index) = diagnostic.normalizedCommutator;
        normalizedEigenvalueGap(index) = diagnostic.normalizedEigenvalueGap;
        directionDMagnitude(index) = abs(diagnostic.criticalDirection(1));
        directionQMagnitude(index) = abs(diagnostic.criticalDirection(2));
        directionQRelativePhase(index) = angle( ...
            conj(diagnostic.criticalDirection(1)) * ...
            diagnostic.criticalDirection(2));
        classificationStatus(index) = diagnostic.classificationStatus;
        classificationIsCertified(index) = ...
            diagnostic.classification.isCertified;
        directionResolved(index) = diagnostic.directionResolved;
        objectiveEnvelopeResolved(index) = ...
            diagnostic.objectiveEnvelopeResolved;
        attributionStatus(index) = diagnostic.attributionStatus;
        overallNumericalStatus(index) = diagnostic.overallNumericalStatus;
    end

    resultTable = table(caseFixture.case_name, caseFixture.frequency_Hz, ...
        normalizedMargin, normalizedLowerBound, normalizedUpperBound, theta, ...
        normalizedHermitianContribution, ...
        normalizedQuadratureContribution, normalizedCommutator, ...
        normalizedEigenvalueGap, directionDMagnitude, ...
        directionQMagnitude, directionQRelativePhase, ...
        classificationStatus, classificationIsCertified, ...
        directionResolved, objectiveEnvelopeResolved, attributionStatus, ...
        overallNumericalStatus, ...
        'VariableNames', {'case_name', 'frequency_Hz', ...
        'normalized_separation_margin', 'normalized_lower_bound', ...
        'normalized_upper_bound', 'optimal_rotation_rad', ...
        'normalized_H_contribution', 'normalized_G_contribution', ...
        'normalized_commutator', 'normalized_eigenvalue_gap', ...
        'critical_direction_d_magnitude', ...
        'critical_direction_q_magnitude', ...
        'critical_direction_q_relative_phase_rad', ...
        'classification_status', 'classification_is_certified', ...
        'direction_resolved', 'objective_envelope_resolved', ...
        'attribution_status', 'overall_numerical_status'});
end

function matrix = matrixFromFixtureRow(row)
    matrix = [ ...
        row.Y11_real + 1i*row.Y11_imag, ...
        row.Y12_real + 1i*row.Y12_imag; ...
        row.Y21_real + 1i*row.Y21_imag, ...
        row.Y22_real + 1i*row.Y22_imag];
end
