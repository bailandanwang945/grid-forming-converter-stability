%RUN_MATHWORKS_GFM_SCR5_DAMPING_TRANSITION Bound vendor time-domain classes.
%
% This script locates an interval whose lower endpoint is classified
% Unstable and upper endpoint Stable by the vendor FindTestOutCome function.
% It does not claim a characteristic-root boundary or a continuous theorem.

    projectRoot = fileparts(fileparts(fileparts(mfilename("fullpath"))));
    externalRoot = fullfile(projectRoot, "external", "mathworks-gfm-r2023b");
    outputDir = fullfile(projectRoot, "results", ...
        "mathworks-gfm-external-validation");
    prepareScript = fullfile(projectRoot, "experiments", ...
        "external-validation", "prepare_mathworks_gfm_active_power_case.m");
    projectFile = fullfile(externalRoot, ...
        "PowerConverterCircuitAndControlDesignWithSimscape.prj");
    factorialPath = fullfile(outputDir, ...
        "mathworks_gfm_scr_damping_factorial.json");

    expectedCommit = "a65692b004637acb38b2f8c64db7dcf47efe24c7";
    expectedFactorialHash = ...
        "90173e9ba8f9e554ff7058af2e004a741c37f4ed7340feb78064d045f0033fea";
    mustBeFile(projectFile);
    mustBeFile(prepareScript);
    mustBeFile(factorialPath);
    actualCommit = gitCommit(externalRoot);
    actualFactorialHash = sha256File(factorialPath);
    if actualCommit ~= expectedCommit
        error("gfm:external:UnexpectedCommit", ...
            "MathWorks source commit is %s; expected %s.", ...
            actualCommit, expectedCommit);
    end
    if actualFactorialHash ~= expectedFactorialHash
        error("gfm:external:UnexpectedFactorialArtifact", ...
            "The prerequisite factorial JSON does not match its frozen hash.");
    end

    factorial = jsondecode(fileread(factorialPath));
    lowerDampingPu = 1.056;
    upperDampingPu = 2.0;
    selectedScr = 5.0;
    targetBracketWidthPu = 0.02;
    maximumIterations = 6;
    powerErrorTolerancePu = 0.01;
    lowerPoint = factorialPoint( ...
        factorial.points, selectedScr, lowerDampingPu);
    upperPoint = factorialPoint( ...
        factorial.points, selectedScr, upperDampingPu);
    if lowerPoint.vendorStable || ~upperPoint.vendorStable
        error("gfm:external:InvalidInitialBracket", ...
            "Frozen endpoints must be Unstable at 1.056 and Stable at 2.0 pu.");
    end

    openProject(projectFile);
    if ~isfolder(outputDir)
        mkdir(outputDir);
    end
    checkpointPath = fullfile(outputDir, ...
        "mathworks_gfm_scr5_damping_transition_checkpoint.json");
    trials = repmat(emptyTrial(), maximumIterations, 1);
    completedIterations = 0;
    runStarted = tic;

    while completedIterations < maximumIterations && ...
            upperDampingPu-lowerDampingPu > targetBracketWidthPu
        completedIterations = completedIterations + 1;
        selectedDampingPu = (lowerDampingPu+upperDampingPu)/2.0;
        run(prepareScript);

        in = Simulink.SimulationInput("GridFormingConverter");
        in = in.setModelParameter("StopTime", mat2str(simulationTime));
        in = in.setVariable("testCondition", testCondition);
        in = in.setVariable("gridInverter", gridInverter);
        in = in.setVariable("grid", grid);
        in = in.setVariable("transformer", transformer);
        in = in.setVariable("TransmissionLine", TransmissionLine);
        in = in.setVariable("shortCircuit", shortCircuit);
        in = in.setVariable("localSolverSampleTime", ...
            localSolverSampleTime);
        in = in.setVariable("scrFactorRg", scrFactorRg);
        in = in.setVariable("scrFactorXg", scrFactorXg);
        in = in.setVariable("scrOut", scrOut);
        in = in.setVariable("XbyROut", XbyROut);

        pointStarted = tic;
        out = sim(in);
        pointElapsedSeconds = toc(pointStarted);
        trial = measureTrial(out, selectedScr, selectedDampingPu, ...
            disturbanceTime, simulationTime, powerErrorTolerancePu, ...
            pointElapsedSeconds);
        trials(completedIterations) = trial;
        clear out in;
        bdclose("GridFormingConverter");

        if trial.vendorStable
            upperDampingPu = selectedDampingPu;
        else
            lowerDampingPu = selectedDampingPu;
        end
        writeCheckpoint(checkpointPath, actualCommit, ...
            actualFactorialHash, lowerDampingPu, upperDampingPu, ...
            trials(1:completedIterations));
        fprintf("BOUNDARY_POINT_OK %d/%d D=%.9g OUTCOME=%s WIDTH=%.9g\n", ...
            completedIterations, maximumIterations, selectedDampingPu, ...
            trial.vendorOutcome, upperDampingPu-lowerDampingPu);
    end

    trials = trials(1:completedIterations);
    testedDampingPu = [1.056; [trials.dampingCoefficientPu].'; 2.0];
    testedStable = [false; [trials.vendorStable].'; true];
    [testedDampingPu, order] = sort(testedDampingPu);
    testedStable = testedStable(order);
    firstStableIndex = find(testedStable, 1, "first");
    monotonicClassification = ...
        all(~testedStable(1:firstStableIndex-1)) && ...
        all(testedStable(firstStableIndex:end));
    if ~monotonicClassification
        error("gfm:external:NonmonotonicClassification", ...
            "Tested damping classes are not ordered Unstable then Stable.");
    end
    endpointTrackingAcceptable = [ ...
        trackingAcceptable(lowerPoint, powerErrorTolerancePu); ...
        trackingAcceptable(upperPoint, powerErrorTolerancePu)];
    trialTrackingAcceptable = arrayfun( ...
        @(trial) trackingAcceptable(trial, powerErrorTolerancePu), trials);
    allTrackingAcceptable = [endpointTrackingAcceptable(1); ...
        trialTrackingAcceptable; endpointTrackingAcceptable(2)];
    allTrackingAcceptable = allTrackingAcceptable(order);
    firstTrackingPassIndex = find(allTrackingAcceptable, 1, "first");
    monotonicTrackingGate = ...
        all(~allTrackingAcceptable(1:firstTrackingPassIndex-1)) && ...
        all(allTrackingAcceptable(firstTrackingPassIndex:end));
    if monotonicTrackingGate
        trackingFailureLowerDampingPu = ...
            testedDampingPu(firstTrackingPassIndex-1);
        trackingPassUpperDampingPu = ...
            testedDampingPu(firstTrackingPassIndex);
        trackingBracketWidthPu = ...
            trackingPassUpperDampingPu-trackingFailureLowerDampingPu;
    else
        trackingFailureLowerDampingPu = NaN;
        trackingPassUpperDampingPu = NaN;
        trackingBracketWidthPu = NaN;
    end

    result = struct;
    result.schemaVersion = "gfm-mathworks-scr5-damping-transition/1.0";
    result.generatedAtUtc = string(datetime("now", "TimeZone", "UTC", ...
        "Format", "yyyy-MM-dd'T'HH:mm:ss.SSSXXX"));
    result.source = struct( ...
        "provider", "MathWorks", ...
        "releaseTag", "23.2.1.4", ...
        "commit", actualCommit, ...
        "matlabRelease", string(version("-release")), ...
        "factorialArtifactRelativePath", ...
            "results/mathworks-gfm-external-validation/mathworks_gfm_scr_damping_factorial.json", ...
        "factorialArtifactSha256", actualFactorialHash);
    result.contract = struct( ...
        "scr", selectedScr, ...
        "initialUnstableDampingPu", 1.056, ...
        "initialStableDampingPu", 2.0, ...
        "targetBracketWidthPu", targetBracketWidthPu, ...
        "maximumIterations", maximumIterations, ...
        "midpointRule", "arithmetic", ...
        "classificationFunction", "FindTestOutCome", ...
        "powerErrorTolerancePu", powerErrorTolerancePu, ...
        "simulationInterface", "scalar Simulink.SimulationInput", ...
        "deterministic", true);
    result.result = struct( ...
        "status", "bracketed", ...
        "unstableLowerDampingPu", lowerDampingPu, ...
        "stableUpperDampingPu", upperDampingPu, ...
        "bracketWidthPu", upperDampingPu-lowerDampingPu, ...
        "descriptiveMidpointPu", ...
            (lowerDampingPu+upperDampingPu)/2.0, ...
        "testedClassificationMonotonic", monotonicClassification, ...
        "completedIterations", completedIterations, ...
        "vendorStableUpperEndpointTrackingAcceptable", ...
            trackingAcceptable( ...
                trials([trials.dampingCoefficientPu] == upperDampingPu), ...
                powerErrorTolerancePu), ...
        "vendorStableDoesNotImplyTrackingGate", ...
            any([trials.vendorStable].' & ~trialTrackingAcceptable), ...
        "trackingGateTestedMonotonic", monotonicTrackingGate, ...
        "trackingFailureLowerDampingPu", ...
            trackingFailureLowerDampingPu, ...
        "trackingPassUpperDampingPu", trackingPassUpperDampingPu, ...
        "trackingBracketWidthPu", trackingBracketWidthPu, ...
        "trackingTargetWidthAchieved", ...
            trackingBracketWidthPu <= targetBracketWidthPu);
    result.trials = trials;
    result.performance = struct( ...
        "newSimulationCount", completedIterations, ...
        "elapsedSeconds", toc(runStarted));
    result.scope = struct( ...
        "claimLevel", ...
            "vendor-time-domain-classification-transition-bracket", ...
        "closedLoopEigenvalueBoundary", false, ...
        "continuousStabilityProof", false, ...
        "projectTrackingTransitionTargetEstablished", false, ...
        "uniqueCausalMechanismIdentified", false, ...
        "physicalHardwareValidation", false, ...
        "paperSufficientConditionEvaluated", false);

    jsonPath = fullfile(outputDir, ...
        "mathworks_gfm_scr5_damping_transition.json");
    csvPath = fullfile(outputDir, ...
        "mathworks_gfm_scr5_damping_transition_trials.csv");
    writeText(jsonPath, jsonencode(result, PrettyPrint=true));
    writetable(struct2table(trials), csvPath);
    delete(checkpointPath);
    fprintf("MATHWORKS_GFM_SCR5_DAMPING_TRANSITION_OK\n");
    fprintf("BRACKET=[%.9g, %.9g] WIDTH=%.9g\n", ...
        lowerDampingPu, upperDampingPu, upperDampingPu-lowerDampingPu);
    fprintf("JSON=%s\n", jsonPath);
    fprintf("CSV=%s\n", csvPath);

function point = factorialPoint(points, scr, dampingPu)
    match = find(abs([points.scr]-scr) < 1.0e-12 & ...
        abs([points.dampingCoefficientPu]-dampingPu) < 1.0e-12);
    if numel(match) ~= 1
        error("gfm:external:MissingFactorialEndpoint", ...
            "Expected exactly one frozen factorial endpoint.");
    end
    point = points(match);
end

function trial = measureTrial(out, scr, dampingPu, disturbanceTime, ...
        simulationTime, powerErrorTolerancePu, elapsedSeconds)
    logs = out.LogsoutGridFormingConverter;
    time = double(logs.get("Pmeas").Values.Time);
    activePower = double(logs.get("Pmeas").Values.Data);
    activePowerReference = double(logs.get("Pref").Values.Data);
    frequency = double(logs.get("Freq").Values.Data);
    voltageD = double(logs.get("Vgd").Values.Data);
    voltageQ = double(logs.get("Vgq").Values.Data);
    currentD = double(logs.get("Igd").Values.Data);
    currentQ = double(logs.get("Igq").Values.Data);
    afterStep = time >= disturbanceTime;
    powerError = abs(activePower-activePowerReference);
    lastViolation = find(afterStep & ...
        powerError > powerErrorTolerancePu, 1, "last");
    if isempty(lastViolation)
        settlingTime = 0.0;
    elseif lastViolation < numel(time)
        settlingTime = time(lastViolation+1)-disturbanceTime;
    else
        settlingTime = NaN;
    end
    voltageMagnitude = hypot(voltageD, voltageQ);
    currentMagnitude = hypot(currentD, currentQ);
    vendorOutcome = string(FindTestOutCome(activePower, voltageD, frequency));

    trial = struct( ...
        "scr", scr, ...
        "dampingCoefficientPu", dampingPu, ...
        "vendorOutcome", vendorOutcome, ...
        "vendorStable", vendorOutcome == "Stable", ...
        "activePowerSettlingTimeS", settlingTime, ...
        "activePowerFinalAbsoluteErrorPu", powerError(end), ...
        "frequencyMaximumDeviationHz", ...
            max(abs(frequency(afterStep)-50.0)), ...
        "voltageMagnitudeMinimumPu", min(voltageMagnitude(afterStep)), ...
        "voltageMagnitudeMaximumPu", max(voltageMagnitude(afterStep)), ...
        "currentMagnitudeMaximumPu", max(currentMagnitude(afterStep)), ...
        "allReportedSignalsFinite", all(isfinite([ ...
            activePower; activePowerReference; frequency; ...
            voltageD; voltageQ; currentD; currentQ])), ...
        "elapsedSeconds", elapsedSeconds, ...
        "simulationTimeS", simulationTime);
end

function trial = emptyTrial()
    trial = struct( ...
        "scr", NaN, "dampingCoefficientPu", NaN, ...
        "vendorOutcome", "", "vendorStable", false, ...
        "activePowerSettlingTimeS", NaN, ...
        "activePowerFinalAbsoluteErrorPu", NaN, ...
        "frequencyMaximumDeviationHz", NaN, ...
        "voltageMagnitudeMinimumPu", NaN, ...
        "voltageMagnitudeMaximumPu", NaN, ...
        "currentMagnitudeMaximumPu", NaN, ...
        "allReportedSignalsFinite", false, ...
        "elapsedSeconds", NaN, "simulationTimeS", NaN);
end

function acceptable = trackingAcceptable(point, powerErrorTolerancePu)
    acceptable = point.vendorStable && ...
        isfinite(point.activePowerSettlingTimeS) && ...
        point.activePowerFinalAbsoluteErrorPu <= powerErrorTolerancePu;
end

function writeCheckpoint(filePath, sourceCommit, factorialHash, ...
        lowerDampingPu, upperDampingPu, trials)
    checkpoint = struct( ...
        "schemaVersion", ...
            "gfm-mathworks-scr5-damping-transition-checkpoint/1.0", ...
        "sourceCommit", sourceCommit, ...
        "factorialArtifactSha256", factorialHash, ...
        "unstableLowerDampingPu", lowerDampingPu, ...
        "stableUpperDampingPu", upperDampingPu, ...
        "completedIterations", numel(trials), ...
        "trials", trials);
    writeText(filePath, jsonencode(checkpoint, PrettyPrint=true));
end

function commit = gitCommit(repositoryRoot)
    command = sprintf('git -C "%s" rev-parse HEAD', repositoryRoot);
    [status, output] = system(command);
    if status ~= 0
        error("gfm:external:GitUnavailable", ...
            "Cannot resolve the external source commit: %s", output);
    end
    commit = string(strtrim(output));
end

function hash = sha256File(filePath)
    file = fopen(filePath, "rb");
    if file < 0
        error("gfm:external:UnreadableFile", "Cannot read %s.", filePath);
    end
    cleanup = onCleanup(@() fclose(file));
    bytes = fread(file, Inf, "*uint8");
    digest = java.security.MessageDigest.getInstance("SHA-256");
    digest.update(typecast(bytes, "int8"));
    value = typecast(digest.digest(), "uint8");
    hash = string(lower(reshape(dec2hex(value, 2).', 1, [])));
end

function writeText(filePath, value)
    file = fopen(filePath, "w", "n", "UTF-8");
    if file < 0
        error("gfm:external:UnwritableFile", "Cannot write %s.", filePath);
    end
    cleanup = onCleanup(@() fclose(file));
    fprintf(file, "%s\n", value);
end
