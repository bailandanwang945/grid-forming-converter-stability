%PREPARE_MATHWORKS_GFM_ACTIVE_POWER_CASE Prepare one frozen vendor case.
%
% Required caller variables:
%   externalRoot       - fixed MathWorks repository path
%   selectedScr        - short-circuit ratio
%   selectedDampingPu  - VSM damping coefficient in pu
%
% This script intentionally runs in the caller workspace because the vendor
% input Live Script defines the model parameter structures there. It does not
% open, load, or edit the Simulink model.

    inputScript = fullfile(externalRoot, "Script_Data", ...
        "GridFormingConverterInputParameters.mlx");
    run(inputScript);
    vendorDefaultDampingPu = gridInverter.vsm.dampingCoefficent;
    if abs(vendorDefaultDampingPu - 1.056) > 1.0e-12
        error("gfm:external:UnexpectedDefaultDamping", ...
            "Vendor default damping is %.12g; expected 1.056.", ...
            vendorDefaultDampingPu);
    end
    gridInverter.vsm.dampingCoefficent = selectedDampingPu;

    disturbanceTime = 3.0;
    simulationTime = 8.0;
    localSolverSampleTime = 100.0e-6;
    testCondition.activePowerMethod = 'Virtual Synchronous Machine';
    testCondition.currentLimitMethod = 'Virtual Impedance';
    testCondition.testCondition = 'Change in active power reference';
    testCondition.XbyR = 5.0;
    testCondition.SCR = selectedScr;
    testCondition.faultResistance = 0.5;

    resistance = real(shortCircuit.overallGridImpedance);
    reactance = imag(shortCircuit.overallGridImpedance);
    xByRFactor = sqrt(1.0 + testCondition.XbyR^2);
    scrFactorRg = 1.0/(testCondition.SCR*resistance*xByRFactor);
    scrFactorXg = testCondition.XbyR*scrFactorRg*resistance/reactance;
    scrOut = 1.0/sqrt((scrFactorRg*resistance)^2 + ...
        (scrFactorXg*reactance)^2);
    XbyROut = scrFactorXg*reactance/(scrFactorRg*resistance);

    testCondition.gridVoltageProfile = timetable( ...
        [1.0; 1.0; 1.0], ...
        RowTimes=seconds([0.0; disturbanceTime; simulationTime]));
    testCondition.gridFrequencyProfile = timetable( ...
        [50.0; 50.0; 50.0], ...
        RowTimes=seconds([0.0; disturbanceTime; simulationTime]));
    testCondition.gridPhaseProfile = timetable( ...
        [0.0; 0.0; 0.0], ...
        RowTimes=seconds([0.0; disturbanceTime; simulationTime]));
    testCondition.gfmRealPowerRefProfile = timetable( ...
        [0.0; 0.6; 0.6; 0.8; 0.8], ...
        RowTimes=seconds([0.0; 1.0; disturbanceTime-1.0e-3; ...
            disturbanceTime; simulationTime]));
    testCondition.gfmReactivePowerRefProfile = timetable( ...
        [0.0; 0.3; 0.3; 0.3], ...
        RowTimes=seconds([0.0; 1.0; disturbanceTime; simulationTime]));
    testCondition.localLoadRealProfile = timetable( ...
        [0.7; 0.7; 0.7; 0.7], ...
        RowTimes=seconds([0.0; disturbanceTime; ...
            disturbanceTime+0.1; simulationTime]));
    testCondition.localLoadReactiveProfile = timetable( ...
        [0.4; 0.4; 0.4], ...
        RowTimes=seconds([0.0; disturbanceTime; simulationTime]));
    testCondition.faultTrigger = timetable( ...
        [0.0; 0.0; 0.0], ...
        RowTimes=seconds([0.0; disturbanceTime; simulationTime]));
    testCondition.circuitBreakerTripSignalProfile = timetable( ...
        [0.0; 0.0; 0.0], ...
        RowTimes=seconds([0.0; disturbanceTime; simulationTime]));
