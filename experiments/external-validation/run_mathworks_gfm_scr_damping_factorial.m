%RUN_MATHWORKS_GFM_SCR_DAMPING_FACTORIAL Frozen 2-by-4 external-model study.
%
% This script does not edit the MathWorks model. It tests whether VSM damping
% can remove the SCR=5 instability observed in the preceding three-point
% active-power-step study. Every point uses the same source model, disturbance,
% virtual-impedance mode, X/R ratio, and initialization procedure.

    projectRoot = fileparts(fileparts(fileparts(mfilename("fullpath"))));
    externalRoot = fullfile(projectRoot, "external", "mathworks-gfm-r2023b");
    outputDir = fullfile(projectRoot, "results", ...
        "mathworks-gfm-external-validation");

    expectedCommit = "a65692b004637acb38b2f8c64db7dcf47efe24c7";
    expectedModelHash = ...
        "9cd2abfd5699e92336ceb335414403cb29826da7a4f7ab3abafd581d96c6fac4";
    expectedConditionHash = ...
        "66632a96de03f438bf63ef51afa8d80fcf720cb520431d64f3f8e6756e632823";
    projectFile = fullfile(externalRoot, ...
        "PowerConverterCircuitAndControlDesignWithSimscape.prj");
    modelFile = fullfile(externalRoot, "Models", "GridFormingConverter.slx");
    inputScript = fullfile(externalRoot, "Script_Data", ...
        "GridFormingConverterInputParameters.mlx");
    conditionScript = fullfile(externalRoot, "Script_Data", ...
        "GridFormingConverterTestCondition.mlx");

    mustBeFile(projectFile);
    mustBeFile(modelFile);
    mustBeFile(inputScript);
    mustBeFile(conditionScript);
    actualCommit = gitCommit(externalRoot);
    actualModelHash = sha256File(modelFile);
    actualConditionHash = sha256File(conditionScript);
    if actualCommit ~= expectedCommit
        error("gfm:external:UnexpectedCommit", ...
            "MathWorks source commit is %s; expected %s.", ...
            actualCommit, expectedCommit);
    end
    if actualModelHash ~= expectedModelHash
        error("gfm:external:UnexpectedModelHash", ...
            "GridFormingConverter.slx SHA-256 does not match the frozen source.");
    end
    if actualConditionHash ~= expectedConditionHash
        error("gfm:external:UnexpectedConditionHash", ...
            "GridFormingConverterTestCondition.mlx SHA-256 does not match the frozen source.");
    end

    openProject(projectFile);
    scrValues = [2.5, 5.0];
    dampingValuesPu = [0.6, 1.056, 2.0, 4.0];
    baselineDampingPu = 1.056;
    xByR = 5.0;
    powerErrorTolerancePu = 0.01;
    pointCount = numel(scrValues)*numel(dampingValuesPu);
    points = repmat(emptyPoint(), pointCount, 1);
    if ~isfolder(outputDir)
        mkdir(outputDir);
    end
    checkpointJsonPath = fullfile(outputDir, ...
        "mathworks_gfm_scr_damping_factorial_checkpoint.json");
    checkpointCsvPath = fullfile(outputDir, ...
        "mathworks_gfm_scr_damping_factorial_checkpoint.csv");

    pointIndex = 0;
    batchStarted = tic;
    for scr = scrValues
        for dampingPu = dampingValuesPu
            pointIndex = pointIndex + 1;
            selected = struct( ...
                "activePowerMethod", "Virtual Synchronous Machine", ...
                "currentLimitMethod", "Virtual Impedance", ...
                "SCR", scr, ...
                "XbyR", xByR, ...
                "dampingCoefficientPu", dampingPu, ...
                "testCondition", "Change in active power reference");

            run(inputScript);
            vendorDefaultDampingPu = gridInverter.vsm.dampingCoefficent;
            if abs(vendorDefaultDampingPu - baselineDampingPu) > 1.0e-12
                error("gfm:external:UnexpectedDefaultDamping", ...
                    "Vendor default damping is %.12g; expected %.12g.", ...
                    vendorDefaultDampingPu, baselineDampingPu);
            end
            gridInverter.vsm.dampingCoefficent = dampingPu;
            testCondition.activePowerMethod = char(selected.activePowerMethod);
            testCondition.currentLimitMethod = char(selected.currentLimitMethod);
            testCondition.testCondition = char(selected.testCondition);
            testCondition.XbyR = selected.XbyR;
            testCondition.SCR = selected.SCR;
            [testCondition, disturbanceTime, simulationTime, ...
                localSolverSampleTime, scrFactorRg, scrFactorXg, ...
                scrOut, xByROut] = buildActivePowerStepCondition( ...
                    testCondition, shortCircuit);

            configuration = struct( ...
                "scr", scr, ...
                "dampingCoefficientPu", dampingPu, ...
                "disturbanceTimeS", disturbanceTime, ...
                "simulationTimeS", simulationTime);
            in = Simulink.SimulationInput("GridFormingConverter");
            in = in.setModelParameter( ...
                "StopTime", mat2str(simulationTime));
            in = in.setVariable("testCondition", testCondition);
            in = in.setVariable("gridInverter", gridInverter);
            in = in.setVariable("grid", grid);
            in = in.setVariable("transformer", transformer);
            in = in.setVariable("TransmissionLine", TransmissionLine);
            in = in.setVariable("shortCircuit", shortCircuit);
            in = in.setVariable("localSolverSampleTime", ...
                localSolverSampleTime);
            in = in.setVariable("scrFactorRg", scrFactorRg);
            in = in.setVariable("scrFactorXg", scrFactorXg);
            in = in.setVariable("scrOut", scrOut);
            in = in.setVariable("XbyROut", xByROut);

            pointStarted = tic;
            out = sim(in);
            pointElapsedSeconds = toc(pointStarted);
            points(pointIndex) = measurePoint(out, configuration, ...
                powerErrorTolerancePu, pointElapsedSeconds);
            clear out in;
            bdclose("GridFormingConverter");
            writeCheckpoint(checkpointJsonPath, checkpointCsvPath, ...
                actualCommit, scrValues, dampingValuesPu, ...
                points(1:pointIndex));
            fprintf("POINT_OK %d/%d SCR=%.6g D=%.6g OUTCOME=%s\n", ...
                pointIndex, pointCount, scr, dampingPu, ...
                points(pointIndex).vendorOutcome);
        end
    end
    batchElapsedSeconds = toc(batchStarted);

    stableMatrix = reshape([points.vendorStable], ...
        numel(dampingValuesPu), numel(scrValues)).';
    frequencyDeviationMatrix = reshape( ...
        [points.frequencyMaximumDeviationHz], ...
        numel(dampingValuesPu), numel(scrValues)).';
    scr5StableAtHighDamping = all(stableMatrix(2, 3:4));
    scr2p5StableAcrossTestedDamping = all(stableMatrix(1, :));
    frequencyDeviationNonincreasing = all( ...
        diff(frequencyDeviationMatrix, 1, 2) <= 0, 2);
    classificationDependsOnBothFactors = any( ...
        stableMatrix(1, :) ~= stableMatrix(2, :)) && ...
        any(diff(stableMatrix(2, :)) ~= 0);

    result = struct;
    result.schemaVersion = "gfm-mathworks-scr-damping-factorial/1.0";
    result.generatedAtUtc = string(datetime("now", "TimeZone", "UTC", ...
        "Format", "yyyy-MM-dd'T'HH:mm:ss.SSSXXX"));
    result.source = struct( ...
        "provider", "MathWorks", ...
        "repository", ...
            "https://github.com/simscape/Power-Converter-Circuit-Control-Simscape", ...
        "releaseTag", "23.2.1.4", ...
        "commit", actualCommit, ...
        "modelRelativePath", "Models/GridFormingConverter.slx", ...
        "modelSha256", actualModelHash, ...
        "conditionRelativePath", ...
            "Script_Data/GridFormingConverterTestCondition.mlx", ...
        "conditionSha256", actualConditionHash, ...
        "matlabRelease", string(version("-release")));
    result.contract = struct( ...
        "scrValues", scrValues, ...
        "dampingCoefficientValuesPu", dampingValuesPu, ...
        "vendorDefaultDampingCoefficientPu", baselineDampingPu, ...
        "xByR", xByR, ...
        "activePowerMethod", "Virtual Synchronous Machine", ...
        "currentLimitMethod", "Virtual Impedance", ...
        "testCondition", "Change in active power reference", ...
        "powerErrorTolerancePu", powerErrorTolerancePu, ...
        "simulationInterface", "Simulink.SimulationInput", ...
        "batchMode", ...
            "sequential points because SCR changes nontunable Simscape parameters");
    result.preRegisteredHypothesis = struct( ...
        "statement", ...
            "Increasing VSM damping to 2 or 4 pu stabilizes the SCR=5 point while SCR=2.5 remains stable across the tested damping values.", ...
        "falsifier", ...
            "Reject if either high-damping SCR=5 point is vendor-unstable or any tested SCR=2.5 point is vendor-unstable.");
    result.results = struct( ...
        "scr5StableAtHighDamping", scr5StableAtHighDamping, ...
        "scr2p5StableAcrossTestedDamping", scr2p5StableAcrossTestedDamping, ...
        "hypothesisSupported", ...
            scr5StableAtHighDamping && scr2p5StableAcrossTestedDamping, ...
        "frequencyDeviationNonincreasingByScr", ...
            frequencyDeviationNonincreasing, ...
        "classificationDependsOnBothTestedFactors", ...
            classificationDependsOnBothFactors, ...
        "stableMatrixRowsScrColumnsDamping", stableMatrix, ...
        "frequencyDeviationMatrixHzRowsScrColumnsDamping", ...
            frequencyDeviationMatrix);
    result.points = points;
    result.performance = struct( ...
        "pointCount", pointCount, ...
        "batchElapsedSeconds", batchElapsedSeconds, ...
        "fastRestartRequested", false, ...
        "failedFastRestartAttemptExcluded", true);
    result.scope = struct( ...
        "claimLevel", ...
            "external-fixed-model-two-factor-eight-point-time-domain-screening", ...
        "independentFromTeamAverageDqImplementation", true, ...
        "physicalHardwareValidation", false, ...
        "paperSufficientConditionEvaluated", false, ...
        "uniqueCausalMechanismIdentified", false, ...
        "continuousBoundaryEstablished", false, ...
        "interactionIsStatisticalEstimate", false);

    jsonPath = fullfile(outputDir, ...
        "mathworks_gfm_scr_damping_factorial.json");
    csvPath = fullfile(outputDir, ...
        "mathworks_gfm_scr_damping_factorial_points.csv");
    writeText(jsonPath, jsonencode(result, PrettyPrint=true));
    writetable(struct2table(points), csvPath);
    delete(checkpointJsonPath);
    delete(checkpointCsvPath);

    fprintf("MATHWORKS_GFM_SCR_DAMPING_FACTORIAL_OK\n");
    fprintf("POINTS=%d BATCH_SECONDS=%.6f\n", ...
        pointCount, batchElapsedSeconds);
    fprintf("JSON=%s\n", jsonPath);
    fprintf("CSV=%s\n", csvPath);

function [testCondition, disturbanceTime, simulationTime, ...
        localSolverSampleTime, scrFactorRg, scrFactorXg, ...
        scrOut, xByROut] = buildActivePowerStepCondition( ...
            testCondition, shortCircuit)
    simulationTime = 8.0;
    disturbanceTime = 3.0;
    localSolverSampleTime = 100.0e-6;
    resistance = real(shortCircuit.overallGridImpedance);
    reactance = imag(shortCircuit.overallGridImpedance);
    xByRFactor = sqrt(1.0 + testCondition.XbyR^2);
    scrFactorRg = 1.0/(testCondition.SCR*resistance*xByRFactor);
    scrFactorXg = testCondition.XbyR*scrFactorRg*resistance/reactance;
    scrOut = 1.0/sqrt((scrFactorRg*resistance)^2 + ...
        (scrFactorXg*reactance)^2);
    xByROut = scrFactorXg*reactance/(scrFactorRg*resistance);

    testCondition.faultResistance = 0.5;
    testCondition.gridVoltageProfile = timedProfile( ...
        [1.0, 1.0, 1.0], [0.0, disturbanceTime, simulationTime]);
    testCondition.gridFrequencyProfile = timedProfile( ...
        [50.0, 50.0, 50.0], [0.0, disturbanceTime, simulationTime]);
    testCondition.gridPhaseProfile = timedProfile( ...
        [0.0, 0.0, 0.0], [0.0, disturbanceTime, simulationTime]);
    testCondition.gfmRealPowerRefProfile = timedProfile( ...
        [0.0, 0.6, 0.6, 0.8, 0.8], ...
        [0.0, 1.0, disturbanceTime-1.0e-3, disturbanceTime, simulationTime]);
    testCondition.gfmReactivePowerRefProfile = timedProfile( ...
        [0.0, 0.3, 0.3, 0.3], ...
        [0.0, 1.0, disturbanceTime, simulationTime]);
    testCondition.localLoadRealProfile = timedProfile( ...
        [0.7, 0.7, 0.7, 0.7], ...
        [0.0, disturbanceTime, disturbanceTime+0.1, simulationTime]);
    testCondition.localLoadReactiveProfile = timedProfile( ...
        [0.4, 0.4, 0.4], [0.0, disturbanceTime, simulationTime]);
    testCondition.faultTrigger = timedProfile( ...
        [0.0, 0.0, 0.0], [0.0, disturbanceTime, simulationTime]);
    testCondition.circuitBreakerTripSignalProfile = timedProfile( ...
        [0.0, 0.0, 0.0], [0.0, disturbanceTime, simulationTime]);
end

function profile = timedProfile(values, times)
    profile = timetable(values.', RowTimes=seconds(times.'));
end

function point = measurePoint(out, configuration, powerErrorTolerancePu, ...
        elapsedSeconds)
    logs = out.LogsoutGridFormingConverter;
    time = double(logs.get("Pmeas").Values.Time);
    activePower = double(logs.get("Pmeas").Values.Data);
    activePowerReference = double(logs.get("Pref").Values.Data);
    frequency = double(logs.get("Freq").Values.Data);
    voltageD = double(logs.get("Vgd").Values.Data);
    voltageQ = double(logs.get("Vgq").Values.Data);
    currentD = double(logs.get("Igd").Values.Data);
    currentQ = double(logs.get("Igq").Values.Data);
    afterStep = time >= configuration.disturbanceTimeS;
    powerError = abs(activePower - activePowerReference);
    lastViolation = find(afterStep & ...
        powerError > powerErrorTolerancePu, 1, "last");
    if isempty(lastViolation)
        settlingTime = 0.0;
    elseif lastViolation < numel(time)
        settlingTime = time(lastViolation + 1) - ...
            configuration.disturbanceTimeS;
    else
        settlingTime = NaN;
    end
    voltageMagnitude = hypot(voltageD, voltageQ);
    currentMagnitude = hypot(currentD, currentQ);
    vendorOutcome = string(FindTestOutCome(activePower, voltageD, frequency));

    point = struct( ...
        "scr", configuration.scr, ...
        "dampingCoefficientPu", configuration.dampingCoefficientPu, ...
        "disturbanceTimeS", configuration.disturbanceTimeS, ...
        "simulationTimeS", configuration.simulationTimeS, ...
        "activePowerReferenceFinalPu", activePowerReference(end), ...
        "activePowerFinalPu", activePower(end), ...
        "activePowerFinalAbsoluteErrorPu", powerError(end), ...
        "activePowerSettlingTimeS", settlingTime, ...
        "activePowerMaximumPu", max(activePower(afterStep)), ...
        "activePowerMinimumPu", min(activePower(afterStep)), ...
        "frequencyMaximumDeviationHz", ...
            max(abs(frequency(afterStep) - 50.0)), ...
        "voltageMagnitudeMinimumPu", min(voltageMagnitude(afterStep)), ...
        "voltageMagnitudeMaximumPu", max(voltageMagnitude(afterStep)), ...
        "currentMagnitudeMaximumPu", max(currentMagnitude(afterStep)), ...
        "vendorOutcome", vendorOutcome, ...
        "vendorStable", vendorOutcome == "Stable", ...
        "allReportedSignalsFinite", all(isfinite([ ...
            activePower; activePowerReference; frequency; ...
            voltageD; voltageQ; currentD; currentQ])), ...
        "elapsedSeconds", elapsedSeconds);
end

function point = emptyPoint()
    point = struct( ...
        "scr", NaN, "dampingCoefficientPu", NaN, ...
        "disturbanceTimeS", NaN, "simulationTimeS", NaN, ...
        "activePowerReferenceFinalPu", NaN, "activePowerFinalPu", NaN, ...
        "activePowerFinalAbsoluteErrorPu", NaN, ...
        "activePowerSettlingTimeS", NaN, "activePowerMaximumPu", NaN, ...
        "activePowerMinimumPu", NaN, "frequencyMaximumDeviationHz", NaN, ...
        "voltageMagnitudeMinimumPu", NaN, ...
        "voltageMagnitudeMaximumPu", NaN, ...
        "currentMagnitudeMaximumPu", NaN, "vendorOutcome", "", ...
        "vendorStable", false, "allReportedSignalsFinite", false, ...
        "elapsedSeconds", NaN);
end

function commit = gitCommit(repositoryRoot)
    command = sprintf('git -C "%s" rev-parse HEAD', repositoryRoot);
    [status, output] = system(command);
    if status ~= 0
        error("gfm:external:GitUnavailable", ...
            "Cannot resolve the external source commit: %s", output);
    end
    commit = string(strtrim(output));
end

function hash = sha256File(filePath)
    file = fopen(filePath, "rb");
    if file < 0
        error("gfm:external:UnreadableFile", "Cannot read %s.", filePath);
    end
    cleanup = onCleanup(@() fclose(file));
    bytes = fread(file, Inf, "*uint8");
    digest = java.security.MessageDigest.getInstance("SHA-256");
    digest.update(typecast(bytes, "int8"));
    value = typecast(digest.digest(), "uint8");
    hash = string(lower(reshape(dec2hex(value, 2).', 1, [])));
end

function writeText(filePath, value)
    file = fopen(filePath, "w", "n", "UTF-8");
    if file < 0
        error("gfm:external:UnwritableFile", "Cannot write %s.", filePath);
    end
    cleanup = onCleanup(@() fclose(file));
    fprintf(file, "%s\n", value);
end

function writeCheckpoint(jsonPath, csvPath, sourceCommit, scrValues, ...
        dampingValuesPu, completedPoints)
    checkpoint = struct( ...
        "schemaVersion", "gfm-mathworks-scr-damping-factorial-checkpoint/1.0", ...
        "sourceCommit", sourceCommit, ...
        "scrValues", scrValues, ...
        "dampingCoefficientValuesPu", dampingValuesPu, ...
        "completedPointCount", numel(completedPoints), ...
        "points", completedPoints);
    writeText(jsonPath, jsonencode(checkpoint, PrettyPrint=true));
    writetable(struct2table(completedPoints), csvPath);
end
